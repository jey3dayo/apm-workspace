# What APM renders from an instruction without applyTo: the body with the frontmatter removed and leading
# blank lines stripped (apm_cli/integration/instruction_integrator.py, _convert_to_claude_rules).
function Get-CatalogInstructionsBody {
  param([Parameter(Mandatory = $true)][string]$Path)

  $lines = [System.IO.File]::ReadAllText($Path) -split "`n"
  if ($lines.Count -gt 0 -and $lines[$lines.Count - 1] -eq "") {
    $lines = @($lines | Select-Object -First ($lines.Count - 1))
  }
  $builder = New-Object System.Text.StringBuilder
  $inFrontmatter = $false
  $started = $false
  for ($index = 0; $index -lt $lines.Count; $index++) {
    $line = $lines[$index]
    if ($index -eq 0 -and $line -ceq "---") { $inFrontmatter = $true; continue }
    if ($inFrontmatter) {
      if ($line -ceq "---") { $inFrontmatter = $false }
      continue
    }
    if (-not $started -and $line -eq "") { continue }
    $started = $true
    [void]$builder.Append($line).Append("`n")
  }
  return $builder.ToString()
}

function Get-GitBlobId {
  param([Parameter(Mandatory = $true)][string]$Path)

  $blobId = & git hash-object --no-filters -- $Path 2>$null
  if ($LASTEXITCODE -ne 0 -or -not $blobId) { return $null }
  return ([string]$blobId).Trim()
}

# Blob ids of every guide body an earlier catalog sync could have copied into a root: each committed catalog/AGENTS.md
# and the current instruction body. Outside a git checkout only the current body is known.
function Get-LegacyCatalogInstructionsBlobs {
  $blobs = New-Object System.Collections.Generic.HashSet[string]
  $bodyPath = [System.IO.Path]::GetTempFileName()
  try {
    $body = Get-CatalogInstructionsBody -Path (Get-TrackedCatalogInstructionsPath)
    [System.IO.File]::WriteAllText($bodyPath, $body, (New-Object System.Text.UTF8Encoding $false))
    $currentBlob = Get-GitBlobId -Path $bodyPath
    if ($currentBlob) { [void]$blobs.Add($currentBlob) }
  }
  finally {
    Remove-Item -LiteralPath $bodyPath -Force -ErrorAction SilentlyContinue
  }
  $rawLines = & git -C $WorkspaceDir log --all --format= --raw --no-abbrev -- "$CatalogDirName/AGENTS.md" 2>$null
  if ($LASTEXITCODE -eq 0) {
    foreach ($rawLine in @($rawLines)) {
      $fields = ([string]$rawLine) -split '\s+'
      if ($fields.Count -ge 4 -and $fields[3] -notmatch '\A0+\z') { [void]$blobs.Add($fields[3]) }
    }
  }
  $instructionLines = & git -C $WorkspaceDir log --all --format= --raw --no-abbrev -- "$CatalogDirName/.apm/instructions/$CatalogInstructionsFileName" 2>$null
  if ($LASTEXITCODE -eq 0) {
    $versionPath = [System.IO.Path]::GetTempFileName()
    $renderedPath = [System.IO.Path]::GetTempFileName()
    # Native output is decoded with the console code page, which is not UTF-8 by default on Windows.
    $previousOutputEncoding = [Console]::OutputEncoding
    [Console]::OutputEncoding = New-Object System.Text.UTF8Encoding $false
    try {
      foreach ($rawLine in @($instructionLines | Select-Object -Unique)) {
        $fields = ([string]$rawLine) -split '\s+'
        if ($fields.Count -lt 4 -or $fields[3] -match '\A0+\z') { continue }
        $versionText = & git -C $WorkspaceDir cat-file blob $fields[3] 2>$null
        if ($LASTEXITCODE -ne 0) { continue }
        [System.IO.File]::WriteAllText($versionPath, ((@($versionText) -join "`n") + "`n"), (New-Object System.Text.UTF8Encoding $false))
        [System.IO.File]::WriteAllText($renderedPath, (Get-CatalogInstructionsBody -Path $versionPath), (New-Object System.Text.UTF8Encoding $false))
        $versionBlob = Get-GitBlobId -Path $renderedPath
        if ($versionBlob) { [void]$blobs.Add($versionBlob) }
      }
    }
    finally {
      [Console]::OutputEncoding = $previousOutputEncoding
      Remove-Item -LiteralPath $versionPath, $renderedPath -Force -ErrorAction SilentlyContinue
    }
  }
  return , $blobs
}

