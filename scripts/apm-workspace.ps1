function Invoke-ValidateCatalog {
  Ensure-WorkspaceRepo
  Ensure-WorkspaceScaffold

  $hasFailure = $false
  $sourceSkillIds = @(Get-TrackedCatalogSkillIds)
  $sourceAgentPaths = @(Get-ManagedAgentRelativePaths)
  $sourceCommandPaths = @(Get-ManagedCommandRelativePaths)
  $sourceRulePaths = @(Get-ManagedRuleRelativePaths)
  $trackedInstructionsPath = Get-TrackedCatalogInstructionsPath
  $trackedManifest = Join-Path (Get-TrackedCatalogDir) "apm.yml"
  $trackedReadme = Join-Path (Get-TrackedCatalogDir) "README.md"

  if (-not (Test-Path -LiteralPath $trackedManifest)) {
    Write-ErrorLine ("Tracked catalog manifest is missing: {0}" -f $trackedManifest)
    $hasFailure = $true
  }

  if (-not (Test-Path -LiteralPath $trackedReadme)) {
    Write-ErrorLine ("Tracked catalog README is missing: {0}" -f $trackedReadme)
    $hasFailure = $true
  }

  if (-not (Test-ManifestHasCatalogReference)) {
    Write-ErrorLine "Global apm.yml is missing the managed catalog ref"
    $hasFailure = $true
  }

  if (-not (Test-Path -LiteralPath $trackedInstructionsPath -PathType Leaf)) {
    Write-ErrorLine ("Tracked catalog is missing instructions: {0}" -f $trackedInstructionsPath)
    $hasFailure = $true
  }
  else {
    $instructionLines = @([System.IO.File]::ReadAllText($trackedInstructionsPath) -split "\r?\n")
    $hasDescription = $false
    if ($instructionLines.Count -gt 0 -and $instructionLines[0] -ceq "---") {
      for ($lineIndex = 1; $lineIndex -lt $instructionLines.Count; $lineIndex++) {
        if ($instructionLines[$lineIndex] -ceq "---") { break }
        if ($instructionLines[$lineIndex] -cmatch '\Adescription:\s*\S') { $hasDescription = $true }
      }
    }
    if (-not $hasDescription) {
      Write-ErrorLine ("Catalog instructions need YAML frontmatter with a description: {0}" -f $trackedInstructionsPath)
      $hasFailure = $true
    }
    if ([string]::IsNullOrWhiteSpace((Get-CatalogInstructionsBody -Path $trackedInstructionsPath))) {
      Write-ErrorLine ("Catalog instructions have no body: {0}" -f $trackedInstructionsPath)
      $hasFailure = $true
    }
  }

  $legacyInstructionsPath = Join-Path (Get-TrackedCatalogDir) "AGENTS.md"
  if ($null -ne (Get-Item -LiteralPath $legacyInstructionsPath -Force -ErrorAction SilentlyContinue)) {
    Write-ErrorLine ("catalog/AGENTS.md is no longer deployed; edit {0} instead" -f $trackedInstructionsPath)
    $hasFailure = $true
  }

  $instructionRuleName = $CatalogInstructionsFileName -replace '\.instructions\.md\z', '.md'
  foreach ($rulesRoot in @((Get-TrackedCatalogRulesRoot), (Get-TrackedCatalogClaudeRulesRoot))) {
    $collidingRule = Join-Path $rulesRoot $instructionRuleName
    if (Test-Path -LiteralPath $collidingRule) {
      Write-ErrorLine ("Catalog rule collides with the Claude rule APM writes for the catalog instructions: {0}" -f $collidingRule)
      $hasFailure = $true
    }
  }

  foreach ($rootCheck in @(
      @{ Label = "skills"; Path = (Get-TrackedCatalogSkillsRoot) },
      @{ Label = "agents"; Path = (Get-TrackedCatalogAgentsRoot) },
      @{ Label = "commands"; Path = (Get-TrackedCatalogCommandsRoot) },
      @{ Label = "rules"; Path = (Get-TrackedCatalogRulesRoot) }
    )) {
    if (-not (Test-Path -LiteralPath $rootCheck.Path)) {
      Write-ErrorLine ("Tracked catalog is missing {0}: {1}" -f $rootCheck.Label, $rootCheck.Path)
      $hasFailure = $true
    }
  }

  if ($sourceSkillIds.Count -eq 0) {
    Write-ErrorLine "Tracked catalog has no managed skills"
    $hasFailure = $true
  }

  $apmDirClaimMessage = Get-CatalogApmDirClaimMessage
  if ($apmDirClaimMessage) {
    Write-ErrorLine $apmDirClaimMessage
    $hasFailure = $true
  }

  $claudeRulesRoot = Get-TrackedCatalogClaudeRulesRoot
  $claudeRuleCount = 0
  if (Test-Path -LiteralPath $claudeRulesRoot -PathType Container) {
    $claudeRuleLeafNames = @(Get-RelativeFilePaths -RootDir $claudeRulesRoot | ForEach-Object { ($_ -split '/')[-1] })
    $regularRuleLeafNames = @(Get-RelativeFilePaths -RootDir (Get-TrackedCatalogRulesRoot) | ForEach-Object { ($_ -split '/')[-1] })
    foreach ($claudeRuleLeafName in $claudeRuleLeafNames) {
      if ($regularRuleLeafNames -ccontains $claudeRuleLeafName) {
        Write-ErrorLine ("Claude rules file name collides with catalog rules: {0}" -f $claudeRuleLeafName)
        $hasFailure = $true
      }
    }
    $claudeRuleCount = $claudeRuleLeafNames.Count
  }

  if ($hasFailure) {
    throw "Catalog validation failed"
  }

  Write-SuccessLine ("Catalog validation passed ({0} skills, {1} agents, {2} commands, {3} rules, {4} claude-rules)" -f $sourceSkillIds.Count, $sourceAgentPaths.Count, $sourceCommandPaths.Count, $sourceRulePaths.Count, $claudeRuleCount)
}

function Get-LearningIntakeReportDate {
  param([string]$ReportName)

  $match = [regex]::Match($ReportName, '^(?<y>[0-9]{4})(?<m>0[1-9]|1[0-2])(?<d>0[1-9]|[12][0-9]|3[01])-')
  if (-not $match.Success) {
    $match = [regex]::Match($ReportName, '^(?<y>[0-9]{4})-(?<m>0[1-9]|1[0-2])-(?<d>0[1-9]|[12][0-9]|3[01])-')
  }
  if (-not $match.Success) {
    return $null
  }
  return "{0}-{1}-{2}" -f $match.Groups['y'].Value, $match.Groups['m'].Value, $match.Groups['d'].Value
}

