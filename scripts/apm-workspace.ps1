function Get-ManifestApmDependencyReferences {
  $manifestPath = Join-Path $WorkspaceDir "apm.yml"
  if (-not (Test-Path -LiteralPath $manifestPath)) {
    return @()
  }

  function Get-YamlIndentLevel {
    param([string]$Line)

    return ($Line.Length - $Line.TrimStart(' ').Length)
  }

  $lines = @(Get-Content -LiteralPath $manifestPath)
  $result = New-Object System.Collections.Generic.List[string]
  $inDependencies = $false
  $dependenciesIndent = -1
  $inApm = $false
  $apmIndent = -1
  for ($i = 0; $i -lt $lines.Count; $i++) {
    $line = $lines[$i]

    if ($line -match '^(?<indent>\s*)(?<key>[^:#][^:]*):(?:\s*(?<value>.*))?$') {
      $indentLevel = $Matches['indent'].Length
      $key = $Matches['key'].Trim()

      if ($indentLevel -eq 0) {
        $inDependencies = ($key -eq 'dependencies')
        $dependenciesIndent = if ($inDependencies) { 0 } else { -1 }
        $inApm = $false
        $apmIndent = -1
        continue
      }

      if ($inDependencies -and $indentLevel -le $dependenciesIndent) {
        $inDependencies = $false
        $dependenciesIndent = -1
        $inApm = $false
        $apmIndent = -1
        continue
      }

      if ($inDependencies) {
        if ($indentLevel -eq ($dependenciesIndent + 2) -and $key -eq 'apm') {
          $inApm = $true
          $apmIndent = $indentLevel
          continue
        }

        if ($inApm -and $indentLevel -le $apmIndent) {
          $inApm = $false
          $apmIndent = -1
        }
      }
    }

    if (-not $inDependencies -or -not $inApm) {
      continue
    }

    # Structured (mapping) entries look like:
    #   - git: owner/repo
    #     ref: <sha>
    #     skills: [...]
    # `ref:` is a sibling key of `git:`, not a `#<sha>` suffix on the value,
    # so pin-status has to be discovered via lookahead rather than a regex
    # on this single line.
    if ($line -match '^(?<indent>\s*)-\s+git:\s+(?<repo>\S+)\s*$') {
      $dashIndent = $Matches['indent'].Length
      if ($dashIndent -lt $apmIndent) {
        continue
      }

      $reference = $Matches['repo']
      if ($reference -match '^jey3dayo/apm-workspace/catalog(?:#|$)' -or $reference -match '^\./') {
        continue
      }

      $siblingIndent = $dashIndent + 2
      $pinnedSha = $null
      $virtualPath = $null
      $blockEnd = $i
      $j = $i + 1
      while ($j -lt $lines.Count) {
        $siblingLine = $lines[$j]
        if ([string]::IsNullOrWhiteSpace($siblingLine)) {
          $j += 1
          continue
        }

        $siblingIndentLevel = Get-YamlIndentLevel -Line $siblingLine
        if ($siblingIndentLevel -le $dashIndent) {
          break
        }

        if ($siblingIndentLevel -eq $siblingIndent -and $siblingLine -match '^\s*ref:\s*(\S+)\s*$') {
          $pinnedSha = $Matches[1]
        }
        if ($siblingIndentLevel -eq $siblingIndent -and $siblingLine -match '^\s*path:\s*(\S+)(?:\s+#.*)?$') {
          $virtualPath = $Matches[1].Trim('"').Trim("'")
        }

        # This entry's own sibling keys (e.g. `skills:` and its nested
        # list items) belong to the mapping, not to the surrounding
        # `dependencies.apm` list -- consume the whole block here so the
        # plain-entry branch below never re-reads a `skills:` list item
        # (such as `- ui-ux-pro-max`) as if it were its own dependency.
        $blockEnd = $j
        $j += 1
      }

      $canonicalReference = if ($virtualPath) { "$reference/$virtualPath" } else { $reference }
      if ($pinnedSha) {
        $canonicalReference = "$canonicalReference#$pinnedSha"
      }
      if (-not $result.Contains($canonicalReference)) {
        $result.Add($canonicalReference)
      }
      $i = $blockEnd
      continue
    }

    # Plain entries may carry a trailing YAML comment (` # ...`); strip it
    # so the captured reference is the bare value (optionally `#<sha>`
    # pinned) rather than the comment text.
    if ($line -match '^\s*-\s+(\S+)(?:\s+#.*)?\s*$') {
      if ((Get-YamlIndentLevel -Line $line) -lt $apmIndent) {
        continue
      }

      $reference = $Matches[1]
      if ($reference -match '^jey3dayo/apm-workspace/catalog(?:#|$)') {
        continue
      }
      if ($reference -match '^\.\/') {
        continue
      }
      if (-not $result.Contains($reference)) {
        $result.Add($reference)
      }
    }
  }

  return $result.ToArray()
}

# Returns the set of forms a `git:` reference from apm.yml could appear as in
# the lockfile's repo_url, so alias lookups can match apm's canonical form
# without knowing in advance which form the manifest author used:
#   - the raw reference itself
#   - the gist key (https://gist.github.com/<owner>/<id>.git -> <owner>/<id>)
#   - the canonical form apm records in apm.lock.yaml's repo_url: the scheme
#     and a trailing .git are dropped, github.com (the default host) is
#     dropped entirely (https://github.com/owner/repo(.git) -> owner/repo),
#     a non-default host keeps its FQDN (https://gitlab.com/acme/repo(.git)
#     -> gitlab.com/acme/repo), and an SCP-style ref
#     (git@host:owner/repo.git) becomes host/owner/repo
function Get-GitReferenceCandidateKeys {
  param(
    [Parameter(Mandatory = $true)]
    [string]$Reference,

    [string]$Path
  )

  $keys = New-Object 'System.Collections.Generic.HashSet[string]'
  $hasPath = -not [string]::IsNullOrWhiteSpace($Path)
  $lookupReference = if ($hasPath) { "$Reference/$Path" } else { $Reference }
  $null = $keys.Add($lookupReference)

  if ($Reference -match '^https://gist\.github\.com/') {
    $gistKey = $Reference -replace '^https://gist\.github\.com/', ''
    $gistKey = $gistKey -replace '\.git(?=/|$)', ''
    if ($hasPath) {
      $gistKey = "$gistKey/$Path"
    }
    $null = $keys.Add($gistKey)
  }

  if ($Reference -match '^https://') {
    $working = $Reference -replace '^https://', ''
    $working = $working -replace '\.git(?=/|$)', ''
    $working = $working -replace '/$', ''
    $working = $working -replace '^github\.com/', ''
    if ($hasPath) {
      $working = "$working/$Path"
    }
    $null = $keys.Add($working)
  } elseif ($Reference -match '^git@') {
    $working = $Reference -replace '^git@', ''
    $working = $working -replace '\.git(?=/|$)', ''
    $working = [regex]::new(':').Replace($working, '/', 1)
    if ($hasPath) {
      $working = "$working/$Path"
    }
    $null = $keys.Add($working)
  }

  return $keys
}

