function Write-DependencyState {
  $result = Get-ApmReadOnlyOutput -Arguments @("deps", "list", "-g")
  Write-Host $result.Output
  if ($result.ExitCode -eq 0) { return }
  $normalized = ($result.Output -replace '\s+', ' ').Trim()
  if ($normalized -ne "[x] Error listing dependencies: Invalid local package path '': path segments must not be empty") {
    throw "apm deps list -g failed."
  }
  $lockPath = Join-Path $WorkspaceDir "apm.lock.yaml"
  $localFiles = $false
  $hasLocalFiles = $false
  foreach ($line in (Get-Content -LiteralPath $lockPath)) {
    if ($line -eq 'local_deployed_files:') { $localFiles = $true; continue }
    if ($localFiles -and $line -match '^ *- ') { $hasLocalFiles = $true; break }
    if ($localFiles -and $line -match '^\S') { break }
  }
  if (-not $hasLocalFiles) {
    throw "apm deps list -g failed."
  }
  Write-WarnLine "Known local self-entry failure: using deps tree with reduced orphan detection. Prune preview below is read-only and may include declared packages; no deletion is authorized by this report."
  & apm deps tree -g
  if ($LASTEXITCODE -ne 0) { throw "apm deps tree -g failed." }
  Write-Host (Get-PrunePreview)
}

function Get-AgentsDifferingFromCatalog {
  param(
    [Parameter(Mandatory = $true)]
    [string]$TargetAgentsRoot
  )

  $agentsRoot = Get-TrackedCatalogAgentsRoot
  foreach ($agentRelativePath in (Get-RelativeFilePaths -RootDir $agentsRoot -IncludeHidden)) {
    if (-not $agentRelativePath.EndsWith(".agent.md", [System.StringComparison]::Ordinal)) {
      continue
    }

    $deployedAgent = Join-Path $TargetAgentsRoot ($agentRelativePath.Substring(0, $agentRelativePath.Length - ".agent.md".Length) + ".md")
    $sourceHash = (Get-FileHash -LiteralPath (Join-Path $agentsRoot $agentRelativePath) -Algorithm SHA256).Hash
    $deployedHash = if (Test-Path -LiteralPath $deployedAgent -PathType Leaf) { (Get-FileHash -LiteralPath $deployedAgent -Algorithm SHA256).Hash } else { $null }
    if ($sourceHash -ne $deployedHash) {
      $deployedAgent
    }
  }
}

function Invoke-Doctor {
  Require-Apm
  Ensure-WorkspaceRepo
  Ensure-WorkspaceScaffold

  $diagnostics = New-Object System.Collections.Generic.List[string]
  $manifestState = if (Test-Path (Join-Path $WorkspaceDir "apm.yml")) { "present" } else { "missing" }
  Write-Host ("apm: {0}" -f (apm --version))
  Write-Host ("workspace: {0}" -f $WorkspaceDir)
  Write-Host ("manifest: {0}" -f $manifestState)
  $branch = & git -C $WorkspaceDir branch --show-current 2>$null
  if ($LASTEXITCODE -ne 0 -or [string]::IsNullOrWhiteSpace(($branch | Out-String))) {
    $branch = "detached"
  }
  Write-Host ("branch: {0}" -f ($branch | Out-String).Trim())
  Write-Host "remote:"
  & git -C $WorkspaceDir remote -v
  Write-Host "targets:"
  $skillInventory = @(Get-ManagedCatalogSkillInventory)
  $codexMcpConfigPath = Join-Path (Join-Path $HOME ".codex") "config.toml"
  try {
    Test-CodexSkillTargetTree
  }
  catch {
    $diagnostics.Add($_.Exception.Message)
  }

  try {
    Test-AgmsgRosterLink
  }
  catch {
    $diagnostics.Add($_.Exception.Message)
  }

  $knownInstructionBlobs = New-Object System.Collections.Generic.HashSet[string]
  if (Test-Path -LiteralPath (Get-TrackedCatalogInstructionsPath) -PathType Leaf) {
    $knownInstructionBlobs = Get-LegacyCatalogInstructionsBlobs
  }
  $trackedAgentsRoot = Get-TrackedCatalogAgentsRoot
  $trackedCommandsRoot = Get-TrackedCatalogCommandsRoot
  $trackedRulesRoot = Get-TrackedCatalogRulesRoot
  foreach ($target in (Get-ManagedCatalogRuntimeTargets)) {
    $hasSkillsRoot = $target.SkillsRoot -ne "-"
    $hasAgentsFace = -not (($target.PSObject.Properties.Name -contains "AgentsFace") -and $target.AgentsFace -eq "-")
    $skillsRoot = if ($target.PSObject.Properties.Name -contains "SkillsRoot" -and $target.SkillsRoot) { $target.SkillsRoot } else { $target.Root }
    $skillsPath = Join-Path $skillsRoot "skills"
    $hasConfig = $target.ConfigName -ne "-"
    $configPath = Join-Path $target.Root $target.ConfigName
    $agentsPath = Join-Path $target.Root "agents"
    $commandsPath = Join-Path $target.Root "commands"
    $rulesPath = Join-Path $target.Root "rules"
    $skillsState = if (-not $hasSkillsRoot) { "n/a" } elseif (Test-Path $skillsPath) { "present" } else { "missing" }
    $agentsState = if (-not $hasAgentsFace) { "n/a" } elseif (Test-Path $agentsPath) { "present" } else { "missing" }
    $configState = if ($hasConfig) { Get-UserRootState -Path $configPath -KnownBlobs $knownInstructionBlobs } else { "n/a" }
    Write-Host ("  {0}: config={1} agents={2} commands={3} rules={4} skills={5}" -f $target.Name, $configState, $agentsState, $(if (Test-Path $commandsPath) { "present" } else { "missing" }), $(if (Test-Path $rulesPath) { "present" } else { "missing" }), $skillsState)

    # A missing root is expected: Claude reads the guide from its native rule, and a hand-written root stays its owner's.
    if ($configState -eq "not-regular" -and (Test-Path -LiteralPath $configPath -PathType Container)) {
      $diagnostics.Add("Root context has wrong type (directory): $configPath")
    }
    elseif ($configState -eq "legacy") {
      Write-WarnLine ("{0} is still the copy the retired legacy catalog sync wrote; move it aside by hand (docs/native-distribution.md)" -f $configPath)
    }
    elseif ($configState -eq "edited-generated" -and $target.Name -eq "claude") {
      Write-WarnLine ("{0} keeps APM's marker but was edited after compile, so apm compile --clean keeps it and Claude reads the guide from it as well as from the rule; remove the guide and the marker line, or move it aside" -f $configPath)
    }
    elseif ($configState -eq "edited-generated") {
      Write-WarnLine ("{0} keeps APM's marker but was edited after compile, so a redeploy skips the root compile; delete the marker line to keep it as your own file, or move it aside" -f $configPath)
    }
    elseif ($target.Name -eq "claude" -and $configState -eq "generated" -and (Test-Path -LiteralPath (Join-Path $rulesPath ($CatalogInstructionsFileName -replace '\.instructions\.md\z', '.md')) -PathType Leaf)) {
      Write-WarnLine ("{0} is an apm compile output that still sits next to the guide rule, so Claude may read the guide twice; redeploy with section B of docs/native-distribution.md so apm compile -g --clean removes it, and if it stays, it is an older compile output: move it aside" -f $configPath)
    }
    elseif ($target.Name -eq "claude" -and $configState -eq "absent" -and (Test-Path -LiteralPath (Get-TrackedCatalogInstructionsPath) -PathType Leaf)) {
      $guideRulePath = Join-Path $rulesPath ($CatalogInstructionsFileName -replace '\.instructions\.md\z', '.md')
      if (-not (Test-Path -LiteralPath $guideRulePath -PathType Leaf)) {
        Write-WarnLine ("Claude has neither {0} nor the guide rule {1}; redeploy with section B of docs/native-distribution.md" -f $configPath, $guideRulePath)
      }
    }
    if ($hasAgentsFace -and (Test-Path -LiteralPath $trackedAgentsRoot -PathType Container) -and -not (Test-Path -LiteralPath $agentsPath -PathType Container)) {
      $diagnostics.Add("Required catalog output is missing or has wrong type (directory): $agentsPath")
    }
    elseif (($target.PSObject.Properties.Name -contains "AgentsFace") -and $target.AgentsFace -eq "apm") {
