function Get-ManifestShaPins {
  $manifestPath = Join-Path $WorkspaceDir "apm.yml"
  if (-not (Test-Path -LiteralPath $manifestPath)) {
    return @()
  }

  $pins = New-Object System.Collections.Generic.List[object]
  $inDependencies = $false
  $inApm = $false
  $entry = ""
  foreach ($line in (Get-Content -LiteralPath $manifestPath)) {
    if ($line -match '^\s*(#|$)') {
      continue
    }
    if ($line -match '^\S') {
      $inDependencies = ($line -match '^dependencies:')
      $inApm = $false
      continue
    }
    if (-not $inDependencies) {
      continue
    }
    if ($line -match '^  [^\s-]') {
      $inApm = ($line -match '^  apm:')
      $entry = ""
      continue
    }
    if (-not $inApm) {
      continue
    }

    if ($line -match '^    -\s+(?<value>.+)$') {
      $entry = ""
      $value = $Matches['value']
      if ($value -match '^git:\s+(?<repo>.+)$') {
        $entry = ($Matches['repo'] -replace '\s+#.*$', '')
        $entryKeys = @(Get-GitReferenceCandidateKeys -Reference $entry)
        continue
      }
      $value = ($value -replace '\s+#.*$', '')
      $hashIndex = $value.IndexOf('#')
      if ($hashIndex -gt 0) {
        $pathEntry = $value.Substring(0, $hashIndex)
        $pins.Add([pscustomobject]@{ Entry = $pathEntry; Ref = $value.Substring($hashIndex + 1); Mode = "path"; Keys = @($pathEntry) })
      }
      continue
    }

    if ($entry -ne "" -and $line -match '^      ref:\s+(?<ref>.+)$') {
      $pins.Add([pscustomobject]@{ Entry = $entry; Ref = ($Matches['ref'] -replace '\s+#.*$', ''); Mode = "repo"; Keys = $entryKeys })
    }
  }

  return @($pins | Where-Object { $_.Ref -cmatch '^[0-9a-f]{7,40}$' })
}

# Deploys resolve from apm.lock.yaml records offline, so a hand-bumped SHA pin
# in apm.yml that the lock does not carry deploys the old commit with exit 0.
function Test-ManifestShaPinsLocked {
  $pins = @(Get-ManifestShaPins)
  if ($pins.Count -eq 0) {
    return
  }

  $hint = "apm.yml SHA pins differ from apm.lock.yaml; update the pinned entries of apm.lock.yaml to the same commits (no task re-resolves the root lock on a native HOME)."
  $lockPath = Join-Path $WorkspaceDir "apm.lock.yaml"
  if (-not (Test-Path -LiteralPath $lockPath)) {
    Write-ErrorLine "Lock file not found: $lockPath"
    throw $hint
  }

  $records = @(Get-LockedExternalSkillRecords)
  $unmatched = 0
  foreach ($pin in $pins) {
    $own = @($records | Where-Object {
        $key = if ($pin.Mode -eq "repo") { $_.Repo } elseif ($_.Path) { "$($_.Repo)/$($_.Path)" } else { $_.Repo }
        $pin.Keys | Where-Object { $_ -ieq $key }
      })
    $reason = if ($own.Count -eq 0) {
      "no lock record"
    }
    elseif (@($own | Where-Object { -not $_.Commit.StartsWith($pin.Ref, [System.StringComparison]::Ordinal) }).Count -gt 0) {
      "lock records a different commit"
    }
    if ($reason) {
      Write-ErrorLine "apm.yml pin not in apm.lock.yaml: $($pin.Entry)#$($pin.Ref) ($reason)"
      $unmatched++
    }
  }

  if ($unmatched -gt 0) {
    throw $hint
  }
}

