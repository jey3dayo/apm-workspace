      }
    }
    if ((Test-Path -LiteralPath $trackedCommandsRoot -PathType Container) -and -not (Test-Path -LiteralPath $commandsPath -PathType Container)) {
      $diagnostics.Add("Required catalog output is missing or has wrong type (directory): $commandsPath")
    }
    if ((Test-Path -LiteralPath $trackedRulesRoot -PathType Container) -and -not (Test-Path -LiteralPath $rulesPath -PathType Container)) {
      $diagnostics.Add("Required catalog output is missing or has wrong type (directory): $rulesPath")
    }
    if ($target.Name -eq "claude") {
      $trackedClaudeRulesRoot = Get-TrackedCatalogClaudeRulesRoot
      if (Test-Path -LiteralPath $trackedClaudeRulesRoot -PathType Container) {
        foreach ($claudeRuleFile in (Get-ChildItem -LiteralPath $trackedClaudeRulesRoot -File)) {
          $claudeRulePath = Join-Path $rulesPath $claudeRuleFile.Name
          if (-not (Test-Path -LiteralPath $claudeRulePath -PathType Leaf)) {
            $diagnostics.Add("Required catalog output is missing or has wrong type (file): $claudeRulePath")
          }
        }
      }
    }
    if ($hasSkillsRoot -and -not (Test-Path -LiteralPath $skillsPath -PathType Container)) {
      $diagnostics.Add("Required catalog output is missing or has wrong type (directory): $skillsPath")
    }
  }
  Write-Host ("opencode instructions: {0}" -f (Get-UserRootState -Path $OpencodeInstructionsOutput -KnownBlobs $knownInstructionBlobs))
  foreach ($missingPath in @(Test-CatalogLockDeployedFiles -LockPath (Join-Path $WorkspaceDir "apm.lock.yaml") -HomeDir $HOME)) {
    $diagnostics.Add("Catalog file recorded in apm.lock.yaml is missing: ~/$missingPath")
  }
  Write-Host ("codex mcp config: {0}" -f $(if (Test-Path $codexMcpConfigPath) { "present" } else { "missing" }))
  Write-Host ("target skill inventory: entries={0}" -f $skillInventory.Count)
  Write-Host ("external pins: unpinned={0}" -f (@(Get-UnpinnedExternalReferences)).Count)
  Write-CatalogSummary
  try {
    Write-DependencyState
  }
  catch {
    $diagnostics.Add($_.Exception.Message)
  }

  if ($diagnostics.Count -gt 0) {
    throw ($diagnostics -join "`n")
  }
}

# The catalog package's lock records (installed from the repository ref, or from a local path as _local/catalog):
# Kind F per deployed_files entry and Kind H (with Hash) per
# deployed_file_hashes entry. Paths are relative to the home directory for a user-scope lock.
function Get-CatalogLockDeployedEntries {
  param([Parameter(Mandatory = $true)][string]$LockPath)

  $entries = New-Object System.Collections.Generic.List[object]
  $name = ""
  $virtualPath = ""
  $mode = ""
  foreach ($rawLine in [System.IO.File]::ReadAllLines($LockPath)) {
    if ($rawLine -match '\A- ' -or $rawLine -match '\A  [a-z_]+:') {
      if ($rawLine -match '\A- ') { $name = ""; $virtualPath = "" }
      $line = $rawLine -replace '\A- ', '  '
      if ($line -ceq "  repo_url: _local/$CatalogDirName") { $virtualPath = $CatalogDirName }
      elseif ($line -match '\A  name: (.*)\z') { $name = $Matches[1] }
      elseif ($line -match '\A  virtual_path: (.*)\z') { $virtualPath = $Matches[1] }
      $mode = if ($line -ceq '  deployed_files:') { "files" } elseif ($line -ceq '  deployed_file_hashes:') { "hashes" } else { "" }
      continue
    }
    if ($rawLine -match '\A[^ ]') { $mode = ""; continue }
    if ($name -cne $CatalogDirName -or $virtualPath -cne $CatalogDirName) { continue }
    if ($mode -eq "files" -and $rawLine -match '\A  - (.*)\z') {
      $entries.Add([pscustomobject]@{ Kind = "F"; Path = $Matches[1]; Hash = $null })
    }
    elseif ($mode -eq "hashes" -and $rawLine -match '\A    (.+): sha256:([0-9a-f]+)\z') {
      $entries.Add([pscustomobject]@{ Kind = "H"; Path = $Matches[1]; Hash = $Matches[2] })
    }
  }
  return , $entries
}

# The lock records what APM itself placed for the catalog; a listed path that is gone means the install was undone.
# A skill or agent deleted from the working catalog stays in the lock until apm.lock.yaml is next updated; such a path is only counted as stale.
# changed counts files the skill sync replaced with the working catalog or a private override, which is expected.
function Test-CatalogLockDeployedFiles {
  param(
    [Parameter(Mandatory = $true)][string]$LockPath,
    [Parameter(Mandatory = $true)][string]$HomeDir
  )

  if (-not (Test-Path -LiteralPath $LockPath -PathType Leaf)) { return @() }
  $missing = New-Object System.Collections.Generic.List[string]
  $listedCount = 0
  $staleCount = 0
  $changedCount = 0
  foreach ($entry in (Get-CatalogLockDeployedEntries -LockPath $LockPath)) {
    $fullPath = Join-Path $HomeDir $entry.Path
    if ($entry.Kind -eq "F") {
      $listedCount++
      if ($null -ne (Get-Item -LiteralPath $fullPath -Force -ErrorAction SilentlyContinue)) { continue }
      if ($entry.Path -match '/(skills|agents)/') { $staleCount++ }
      else { $missing.Add($entry.Path) }
    }
    elseif ((Test-Path -LiteralPath $fullPath -PathType Leaf) -and ((Get-FileHash -LiteralPath $fullPath -Algorithm SHA256).Hash -ne $entry.Hash.ToUpperInvariant())) {
      $changedCount++
    }
  }
  Write-Host ("catalog lock files: listed={0} missing={1} stale={2} changed={3}" -f $listedCount, $missing.Count, $staleCount, $changedCount)
  if ($staleCount -gt 0) {
    Write-WarnLine ("{0} skill or agent file(s) recorded in apm.lock.yaml are gone, as after deleting them from the working catalog; they leave the lock when apm.lock.yaml is next updated." -f $staleCount)
  }
  return @($missing)
}

