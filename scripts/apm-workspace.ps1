function Invoke-SetupHostMcp {
  Require-Command -Name "codex"
  Require-Command -Name "claude"

  $mcpCommandPath = Get-OnePasswordMcpCommand
  if ([string]::IsNullOrWhiteSpace($mcpCommandPath)) {
    throw "1Password MCP command not found. Install or enable the 1Password desktop app MCP first."
  }

  if (Test-CodexOnePasswordMcp -McpCommandPath $mcpCommandPath) {
    Write-Host "Codex 1Password MCP is already configured: $mcpCommandPath"
  } else {
    & codex mcp get 1password *> $null
    if ($LASTEXITCODE -eq 0) {
      & codex mcp remove 1password
      if ($LASTEXITCODE -ne 0) {
        throw "Failed to remove the existing Codex 1Password MCP entry."
      }
    }
    & codex mcp add 1password -- $mcpCommandPath
    if ($LASTEXITCODE -ne 0) {
      throw "Failed to configure the Codex 1Password MCP entry."
    }
  }

  if (Test-ClaudeOnePasswordMcp -McpCommandPath $mcpCommandPath) {
    Write-Host "Claude 1Password MCP is already configured: $mcpCommandPath"
  } else {
    & claude mcp get 1password *> $null
    if ($LASTEXITCODE -eq 0) {
      & claude mcp remove 1password --scope user
      if ($LASTEXITCODE -ne 0) {
        throw "Failed to remove the existing Claude 1Password MCP entry."
      }
    }
    & claude mcp add --scope user 1password -- $mcpCommandPath
    if ($LASTEXITCODE -ne 0) {
      throw "Failed to configure the Claude 1Password MCP entry."
    }
  }

  if (-not (Test-CodexOnePasswordMcp -McpCommandPath $mcpCommandPath)) {
    throw "Codex 1Password MCP verification failed."
  }
  if (-not (Test-ClaudeOnePasswordMcp -McpCommandPath $mcpCommandPath)) {
    throw "Claude 1Password MCP verification failed."
  }
  Write-SuccessLine "Host-local 1Password MCP configuration is current."
}

function Get-LockedExternalSkillRecords {
  $lockPath = Join-Path $WorkspaceDir "apm.lock.yaml"
  if (-not (Test-Path -LiteralPath $lockPath)) {
    throw "Lock file not found: $lockPath"
  }

  function Get-YamlIndentLevel {
    param([string]$Line)

    return ($Line.Length - $Line.TrimStart(' ').Length)
  }

  $records = @()
  $current = @{}
  $inDependencies = $false
  $dependenciesIndent = -1
  $currentRecordIndent = -1
  foreach ($line in (Get-Content -LiteralPath $lockPath)) {
    if ($line -match '^(?<indent>\s*)(?<key>[^:#-][^:]*):(?:\s*(?<value>.*))?$') {
      $indentLevel = $Matches['indent'].Length
      $key = $Matches['key'].Trim()

      if ($indentLevel -eq 0) {
        if ($inDependencies -and $current.ContainsKey('repo_url')) {
          $records += [pscustomobject]$current
          $current = @{}
          $currentRecordIndent = -1
        }

        $inDependencies = ($key -eq 'dependencies')
        $dependenciesIndent = if ($inDependencies) { 0 } else { -1 }
        continue
      }

      if ($inDependencies -and $indentLevel -le $dependenciesIndent) {
        if ($current.ContainsKey('repo_url')) {
          $records += [pscustomobject]$current
        }
        $current = @{}
        $currentRecordIndent = -1
        $inDependencies = $false
        $dependenciesIndent = -1
        continue
      }
    }

    if (-not $inDependencies) {
      continue
    }

    if ($line -match '^(?<indent>\s*)-\s+repo_url:\s+(?<repo>.+)$') {
      if ($current.ContainsKey('repo_url')) {
        $records += [pscustomobject]$current
      }
      $current = @{ repo_url = $Matches['repo'].Trim() }
      $currentRecordIndent = $Matches['indent'].Length
      continue
    }

    if (-not $current.ContainsKey('repo_url')) {
      continue
    }

    $indentLevel = Get-YamlIndentLevel -Line $line
    if ($indentLevel -le $currentRecordIndent) {
      continue
    }

    if ($line -match '^\s+resolved_commit:\s+(.+)$') {
      $current.resolved_commit = $Matches[1].Trim()
      continue
    }

    if ($line -match '^\s+virtual_path:\s+(.+)$') {
      $current.virtual_path = $Matches[1].Trim()
      continue
    }
  }

  if ($current.ContainsKey('repo_url')) {
    $records += [pscustomobject]$current
  }

  $result = New-Object System.Collections.Generic.List[object]
  foreach ($record in $records) {
    if (-not $record.PSObject.Properties.Name.Contains('resolved_commit')) {
      continue
    }

    $result.Add([pscustomobject]@{
      Repo = $record.repo_url
      Path = if ($record.PSObject.Properties.Name.Contains('virtual_path') -and -not [string]::IsNullOrWhiteSpace($record.virtual_path)) { $record.virtual_path } else { "" }
      Commit = $record.resolved_commit
    })
  }

  return $result.ToArray()
}

