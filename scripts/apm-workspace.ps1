function Test-CatalogApmDirRegularFile {
  param(
    [Parameter(Mandatory = $true)]
    $Item
  )

  if ($Item.PSIsContainer -or $Item.LinkType) {
    return $false
  }

  $unixStat = $Item.PSObject.Properties["UnixStat"]
  if ($unixStat -and $null -ne $unixStat.Value) {
    return $unixStat.Value.ItemType -eq "File"
  }

  if ([System.Environment]::OSVersion.Platform -eq "Win32NT") {
    return $true
  }

  # Without UnixStat, ask `test` (no `--`: BSD test rejects it); if it cannot run, fail closed so the entry is claimed.
  try {
    & test -f $Item.FullName
    return $LASTEXITCODE -eq 0
  }
  catch {
    return $false
  }
}

function Get-CatalogApmDirClaimedPaths {
  param(
    [Parameter(Mandatory = $true)]
    [string]$ApmDir
  )

  if (-not (Test-Path -LiteralPath $ApmDir)) {
    return @()
  }

  $rootFullPath = (Resolve-Path -LiteralPath $ApmDir).Path
  # -ErrorAction Stop: an unreadable directory must fail the scan, not hide what it holds.
  $entries = foreach ($item in Get-ChildItem -LiteralPath $ApmDir -Recurse -Force -ErrorAction Stop) {
    if ($item.PSIsContainer -and -not $item.LinkType) {
      continue
    }
    [pscustomobject]@{
      RelativePath = ($item.FullName.Substring($rootFullPath.Length).TrimStart('\', '/')) -replace '\\', '/'
      IsRegularFile = Test-CatalogApmDirRegularFile -Item $item
    }
  }

  $skillDirs = New-Object 'System.Collections.Generic.HashSet[string]' ([System.StringComparer]::Ordinal)
  foreach ($entry in $entries) {
    if ($entry.IsRegularFile -and $entry.RelativePath -cmatch '\Askills/.+/SKILL\.md\z') {
      [void]$skillDirs.Add($entry.RelativePath.Substring(0, $entry.RelativePath.Length - "/SKILL.md".Length))
    }
  }

  $result = New-Object System.Collections.Generic.List[string]
  foreach ($entry in $entries) {
    $relativePath = $entry.RelativePath
    if ($entry.IsRegularFile) {
      if ($relativePath -cmatch '\Aagents/[^/]+\.agent\.md\z') {
        continue
      }
      if ($relativePath -ceq "instructions/$CatalogInstructionsFileName") {
        continue
      }
      if ($relativePath -clike "skills/*") {
        $enclosed = $false
        $parent = $relativePath
        while ($parent.Contains("/")) {
          $parent = $parent.Substring(0, $parent.LastIndexOf("/"))
          if ($skillDirs.Contains($parent)) {
            $enclosed = $true
            break
          }
        }
        if ($enclosed) {
          continue
        }
      }
    }

    $result.Add($relativePath)
  }

  $array = $result.ToArray()
  [Array]::Sort($array)
  return $array
}

function Get-CatalogApmDirClaimMessage {
  $apmDir = Join-Path (Get-TrackedCatalogDir) ".apm"
  $apmDirItem = Get-Item -LiteralPath $apmDir -Force -ErrorAction SilentlyContinue
  if ($apmDirItem -and $apmDirItem.LinkType) {
    return "catalog/.apm is a symlink; validate:catalog needs a real directory there. Replace the link with a directory."
  }

  try {
    $claimedEntry = @(Get-CatalogApmDirClaimedPaths -ApmDir $apmDir) | Select-Object -First 1
  }
  catch {
    return "catalog/.apm could not be fully read, so validate:catalog cannot tell what it holds. Make every entry under catalog/.apm readable first."
  }
  if (-not $claimedEntry) {
    return $null
  }

  if ($claimedEntry -clike "skills/*" -or $claimedEntry -clike "agents/*" -or $claimedEntry -clike "instructions/*") {
    $claimedItem = Get-Item -LiteralPath (Join-Path $apmDir $claimedEntry) -Force -ErrorAction SilentlyContinue
    if ($claimedItem -and (Test-CatalogApmDirRegularFile -Item $claimedItem)) {
      return ("catalog/.apm holds {0}, which the catalog build does not carry: it keeps only files inside a skill directory (one holding SKILL.md), agents named agents/<name>.agent.md and instructions/{1}. Move it into a skill, rename the agent, or merge the instruction into instructions/{1}." -f $claimedEntry, $CatalogInstructionsFileName)
    }
  }

  return ("catalog/.apm holds {0}, but the catalog package carries only catalog/.apm/skills, catalog/.apm/agents and the catalog instruction. Move it out of catalog/.apm." -f $claimedEntry)
}

function Get-ManagedSkillContentDir {
  param(
    [Parameter(Mandatory = $true)]
    [string]$SkillId
  )

  $skillRoot = Get-TrackedCatalogSkillsRoot
  foreach ($segment in (Convert-SkillIdToPathSegments -SkillId $SkillId)) {
    $skillRoot = Join-Path $skillRoot $segment
  }

  if (-not (Test-Path -LiteralPath (Join-Path $skillRoot "SKILL.md"))) {
    throw "Managed catalog skill missing SKILL.md: $skillRoot"
  }

  return $skillRoot
}

function Copy-ManagedSkillIntoCatalog {
  param(
    [Parameter(Mandatory = $true)]
    [string]$SkillId,

    [Parameter(Mandatory = $true)]
    [string]$SkillsRoot
  )

  $sourceDir = Get-ManagedSkillContentDir -SkillId $SkillId
  $destinationDir = $SkillsRoot
  foreach ($segment in (Convert-SkillIdToPathSegments -SkillId $SkillId)) {
    $destinationDir = Join-Path $destinationDir $segment
  }

  Copy-DirectoryContents -SourceDir $sourceDir -DestinationDir $destinationDir
}

