# APM reads a root with Python's universal newlines, so CRLF and a lone CR count as LF; a BOM is kept as text.
function Get-ApmRootText {
  param([Parameter(Mandatory = $true)][string]$Path)

  $text = [System.Text.UTF8Encoding]::new($false).GetString([System.IO.File]::ReadAllBytes($Path))
  return $text.Replace("`r`n", "`n").Replace("`r", "`n")
}

# Mirrors APM's `content.lstrip().startswith(AGENTS_MD_GENERATED_MARKER)` (apm_cli/compilation/user_root_context.py).
function Test-ApmRootMarker {
  param([Parameter(Mandatory = $true)][string]$Path)

  return (Get-ApmRootText -Path $Path).TrimStart($PythonLeadingSpace).StartsWith($ApmGeneratedRootMarker, [System.StringComparison]::Ordinal)
}

# Mirrors apm_cli/compilation/build_id.py has_valid_build_id: the 12-hex Build ID is the sha256 of the file with that
# line removed and the remaining lines joined by "`n", so any edit after compile breaks the match.
function Test-ApmBuildIdValid {
  param([Parameter(Mandatory = $true)][string]$Path)

  $content = Get-ApmRootText -Path $Path
  if ($content.EndsWith("`n")) { $content = $content.Substring(0, $content.Length - 1) }
  $lines = $content -split "`n"
  $buildIdLines = @($lines | Where-Object { $_ -cmatch '^<!-- Build ID: [0-9a-f]{12} -->$' })
  if ($buildIdLines.Count -ne 1) { return $false }
  $hashInput = ($lines | Where-Object { $_ -cnotmatch '^<!-- Build ID: [0-9a-f]{12} -->$' }) -join "`n"
  $sha = [System.Security.Cryptography.SHA256]::Create()
  try {
    $digest = $sha.ComputeHash([System.Text.Encoding]::UTF8.GetBytes($hashInput))
  }
  finally {
    $sha.Dispose()
  }
  $computed = (($digest | ForEach-Object { $_.ToString("x2") }) -join "").Substring(0, 12)
  return ($buildIdLines[0] -ceq "<!-- Build ID: $computed -->")
}

# Classifies a root context file: absent, not-regular, generated (written by apm compile and unchanged since),
# edited-generated (APM's marker kept but edited after compile), legacy (a byte copy of a catalog guide an earlier
# sync wrote), or hand-written (anything else, which only its owner may change).
function Get-UserRootState {
  param(
    [Parameter(Mandatory = $true)][string]$Path,
    [Parameter(Mandatory = $true)][AllowEmptyCollection()][System.Collections.Generic.HashSet[string]]$KnownBlobs
  )

  $item = Get-Item -LiteralPath $Path -Force -ErrorAction SilentlyContinue
  if ($null -eq $item) { return "absent" }
  # pwsh also reports a hard-linked regular file as LinkType HardLink.
  if ($item.LinkType -in @("SymbolicLink", "Junction") -or $item.PSIsContainer) { return "not-regular" }
  if (Test-ApmRootMarker -Path $Path) {
    if (Test-ApmBuildIdValid -Path $Path) { return "generated" }
    return "edited-generated"
  }
  if (Test-LegacyCatalogInstructionsCopy -Path $Path -KnownBlobs $KnownBlobs) { return "legacy" }
  return "hand-written"
}

function Get-SkillIdsFromRoot {
  param(
    [Parameter(Mandatory = $true)]
    [string]$SkillsRoot
  )

  if (-not (Test-Path -LiteralPath $SkillsRoot)) {
    return @()
  }

  $result = New-Object System.Collections.Generic.List[string]
  foreach ($skillFile in (Get-ChildItem -LiteralPath $SkillsRoot -Recurse -Filter "SKILL.md" -File | Sort-Object FullName)) {
    $skillDir = Split-Path -Parent $skillFile.FullName
    $relativePath = $skillDir.Substring($SkillsRoot.Length).TrimStart('\', '/')
    if ([string]::IsNullOrWhiteSpace($relativePath)) {
      continue
    }

    $skillId = ($relativePath -replace '[\\/]', ':')
    if (-not $result.Contains($skillId)) {
      $result.Add($skillId)
    }
  }

  return $result.ToArray()
}

