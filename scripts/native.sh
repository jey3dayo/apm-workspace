#!/usr/bin/env bash
# Native APM distribution: a consumer manifest pins this repository's packages by commit SHA, and `apm install -g`
# followed by `apm compile -g --clean` deploy them. What APM does not deploy is listed in docs/native-distribution.md
# and stays manual; this script adds no sync of its own.
#
# apply targets a disposable HOME and refuses the account's real HOME, its ancestors and the tool state inside it.
# apply --real-home is blocked; migrate is the only command that writes the real HOME, after a clean `rehearse --migrate`
# (docs/native-distribution.md). backup and rehearse only read it.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
ROOT_MANIFEST="$REPO_ROOT/apm.yml"
SOURCE_URL="${APM_NATIVE_SOURCE_URL:-https://github.com/jey3dayo/apm-workspace.git}"
APM_BIN="${APM_BIN:-apm}"
GENERATED_ROOT_MARKER="<!-- Generated by APM CLI from .apm/ primitives -->"
# Roots `apm compile -g` may write. An edited copy that kept APM's marker would be overwritten without notice.
COMPILED_ROOTS=".claude/CLAUDE.md .codex/AGENTS.md .cursor/AGENTS.md"
PROTECTED_SURFACES=".apm .claude .codex .cursor .agents .config .cache .local Library"
# Skills and agents roots the old writer filled. migrate moves them aside (never deletes) before apm install, then
# reinstate_entries puts back whatever apm did not deploy.
MIGRATE_ROOTS=".agents/skills .claude/skills .claude/agents .cursor/agents"
# What apm writes in the real HOME: the migrated roots, rules, the compiled roots, its own state and caches. migrate
# scans only these for links that leave the HOME.
REAL_HOME_WRITE_PATHS=".agents/skills .claude/skills .claude/agents .cursor/agents .claude/rules .codex/rules .cursor/rules
.claude/CLAUDE.md .codex/AGENTS.md .cursor/AGENTS.md .apm .cache/apm Library/Caches/apm"
REAL_HOME_TOOL_DIRS=".agents .claude .codex .cursor .cache Library Library/Caches"
# External dependencies that APM only accepts in the structured form (a Codex native plugin bundle is otherwise
# attempted): <manifest path>=<git repository>:<skill>. render turns `- <manifest path>#<40-hex SHA>` into
# `- git: <repository> / ref: <SHA> / skills: [<skill>]`.
EXTERNAL_PACKAGE_MAP="nanaism/yomiyasu/skills/yomiyasu=nanaism/yomiyasu:yomiyasu"
# Files whose content a migrate must leave byte for byte alone.
MIGRATE_UNTOUCHED_FILES=".codex/config.toml .claude/settings.json"
# Non-secret paths apply can change; backup copies them and rehearse reproduces them in a scratch HOME. Tool configs that
# may hold credentials (~/.codex/config.toml, MCP configs) are not here, which is why apply installs with --only apm.
BACKUP_PATHS=".apm/apm.yml .apm/config.json .apm/apm.lock.yaml .apm/deployment-receipts .claude/skills .claude/agents .claude/rules .claude/commands .claude/CLAUDE.md
.codex/AGENTS.md .codex/rules .cursor/agents .cursor/rules .cursor/AGENTS.md .agents/skills AGENTS.md .config/opencode/AGENTS.md"

usage() {
  cat <<'EOF'
Usage: scripts/native.sh <command> [options]

  plan     [--source-ref REF] [--workspace-only]  Print the consumer manifest and the steps apply would run. Writes nothing.
  render   --source-ref REF [--workspace-only]    Print the consumer manifest to stdout.
  backup   (--home DIR | --real-home) --backup-dir NEW_DIR
                                                 Copy the non-secret paths apply can change, plus the agmsg store.
  rehearse (--home DIR | --real-home) --backup-dir DIR --source-ref REF [--workspace-only] [--migrate]
                                                 Clone a completed backup into a scratch HOME inside DIR, run the same
                                                 install and compile there, and count the files that disappeared.
                                                 --migrate moves the skills and agents roots aside first and puts back what
                                                 apm did not deploy (the steps migrate runs), and fails on any lost file
                                                 other than a .apm-pin.
  apply    --home DIR --source-ref REF [--workspace-only]
                                                 Write the manifest into <HOME>/.apm/apm.yml, then apm install -g --only apm and
                                                 apm compile -g --clean with that HOME, which must be disposable.
                                                 --real-home is blocked; use migrate.
  migrate  (--home DIR | --real-home) --source-ref REF --rehearsal DIR [--workspace-only]
                                                 After a clean rehearse --migrate: move the four roots (.agents/skills,
                                                 .claude/skills, .claude/agents, .cursor/agents) to <root>.bak-<UTC>, install,
                                                 compile and reinstate. Fails and rolls back on any error. Refuses a
                                                 <HOME>/.apm that is a checkout. Prints the UTC stamp and the rollback command.
  migrate-rollback (--home DIR | --real-home) --stamp UTC
                                                 Move the current roots to <root>.native-<UTC> and the <root>.bak-<UTC> back.
                                                 Nothing is deleted.
  reinstate (--home DIR | --real-home) --stamp UTC
                                                 Copy the top-level entries of <root>.bak-<UTC> that the current root lacks back
                                                 into it. Entries already there are left alone.

REF is a commit of this repository (or a full 40-hex SHA). --workspace-only keeps only the catalog and manual-skills
packages and drops external dependencies and MCP servers.
EOF
}

fail() {
  printf 'error: %s\n' "$*" >&2
  exit 1
}

log() {
  printf '%s\n' "$*" >&2
}

resolve_source_sha() {
  local ref="$1" sha
  if sha=$(git -C "$REPO_ROOT" rev-parse --verify --quiet "$ref^{commit}" 2>/dev/null); then
    printf '%s\n' "$sha"
  elif [[ "$ref" =~ ^[0-9a-f]{40}$ ]]; then
    printf '%s\n' "$ref"
  else
    fail "--source-ref $ref is neither a commit of $REPO_ROOT nor a full 40-hex SHA"
  fi
}

# Rewrites the two floating workspace refs (catalog#main, manual-skills#main) into SHA pins, and the packages in
# EXTERNAL_PACKAGE_MAP into the structured form. The other external dependencies are already pinned in apm.yml and pass
# through unchanged. A listed package missing from apm.yml fails the render, so a rename there is not skipped silently.
render_manifest() {
  local sha="$1" workspace_only="$2"
  [ -f "$ROOT_MANIFEST" ] || fail "missing $ROOT_MANIFEST"
  printf '# Rendered by scripts/native.sh from apm.yml with this repository pinned at %s. Do not edit; re-render.\n' "$sha"
  awk -v sha="$sha" -v url="$SOURCE_URL" -v only="$workspace_only" -v map="$EXTERNAL_PACKAGE_MAP" '
    function convert(   i, prefix, rest, pin) {
      for (i = 1; i <= n; i++) {
        prefix = "    - " key[i] "#"
        if (index($0, prefix) != 1) continue
        rest = substr($0, length(prefix) + 1)
        pin = substr(rest, 1, 40)
        if (length(pin) != 40 || pin !~ /^[0-9a-f]+$/) continue
        if (length(rest) > 40 && substr(rest, 41, 1) != " ") continue
        printf "    - git: %s\n      ref: %s\n      skills:\n        - %s\n", repo[i], pin, skill[i]
        converted[i]++
        return 1
      }
      return 0
    }
    BEGIN {
      n = split(map, entries, " ")
      for (i = 1; i <= n; i++) {
        split(entries[i], kv, "=")
        split(kv[2], rs, ":")
        key[i] = kv[1]; repo[i] = rs[1]; skill[i] = rs[2]
      }
    }
    /^[^ #]/ { section = $0; sub(/:.*/, "", section); group = "" }
    section == "dependencies" && /^  [a-z]+:/ { group = $1 }
    /^    - jey3dayo\/apm-workspace\/(catalog|manual-skills)#main[ ]*$/ {
      pkg = $0
      sub(/^.*apm-workspace\//, "", pkg)
      sub(/#main.*$/, "", pkg)
      printf "    - git: %s\n      path: %s\n      ref: %s\n", url, pkg, sha
      pinned[pkg]++
      next
    }
    !only && convert() { next }
    only && section == "dependencies" && group == "mcp:" { next }
    only && section == "dependencies" && group == "apm:" && !/^  apm:/ { next }
    { print }
    END {
      ok = (pinned["catalog"] == 1 && pinned["manual-skills"] == 1)
      if (!only) for (i = 1; i <= n; i++) if (converted[i] != 1) ok = 0
      exit !ok
    }
  ' "$ROOT_MANIFEST" || fail "apm.yml must list jey3dayo/apm-workspace/catalog#main and manual-skills#main exactly once each, and every package of EXTERNAL_PACKAGE_MAP (such as nanaism/yomiyasu/skills/yomiyasu#<40-hex SHA>) exactly once"
}

physical_path() {
  local path="$1" rest=""
  while [ ! -d "$path" ]; do
    rest="/$(basename "$path")$rest"
    path="$(dirname "$path")"
  done
  printf '%s%s\n' "$(cd "$path" && pwd -P)" "$rest"
}

# The account's home from the user database, not $HOME, so a HOME override cannot hide the real one.
# APM_NATIVE_ACCOUNT_HOME stands in for it in tests, which never touch the real one.
user_db_home() {
  local user home
  user="$(id -un)"
  home="$(eval "printf '%s' ~$user")"
  physical_path "$home"
}

account_home() {
  if [ -n "${APM_NATIVE_ACCOUNT_HOME:-}" ]; then
    [ -d "$APM_NATIVE_ACCOUNT_HOME" ] || fail "APM_NATIVE_ACCOUNT_HOME=$APM_NATIVE_ACCOUNT_HOME is not a directory"
    physical_path "$APM_NATIVE_ACCOUNT_HOME"
    return
  fi
  user_db_home
}

# Also checks the user database HOME, so the test override cannot make the real HOME look disposable.
assert_disposable_home() {
  local dir="$1" home surface prefix
  case "/$dir/" in
    */../*) fail "--home $dir must not contain '..'" ;;
  esac
  [ -d "$dir" ] || fail "--home $dir is not an existing directory"
  dir="$(cd "$dir" && pwd -P)"
  assert_ssh_safe_home "$dir"
  for home in "$(account_home)" "$(user_db_home)"; do
    case "$home/" in
      "${dir%/}/"*) fail "--home $dir is the account's HOME or contains it; the cutover is not part of this script (docs/native-distribution.md)" ;;
    esac
    for surface in $PROTECTED_SURFACES; do
      for prefix in "$home/$surface/" "$(physical_path "$home/$surface")/"; do
        case "$dir/" in
          "$prefix"*) fail "--home $dir is inside $home/$surface" ;;
        esac
      done
    done
  done
  printf '%s\n' "$dir"
}

# APM reads a root with Python's splitlines(): CRLF and a lone CR both end a line.
root_lines() {
  awk '{ sub(/\r$/, ""); gsub(/\r/, "\n"); print }' "$1"
}

has_marker() {
  local first
  first="$(root_lines "$1" | LC_ALL=C sed -n '/[^[:space:]]/{p;q;}')"
  [ "${first#"$GENERATED_ROOT_MARKER"}" != "$first" ]
}

# apm_cli/compilation/build_id.py: the 12-hex Build ID is the sha256 of the file without that line, lines joined by
# "\n". Any edit after compile breaks the match.
has_valid_build_id() {
  local pattern='^<!-- Build ID: [0-9a-f]{12} -->$' recorded computed
  recorded="$(root_lines "$1" | grep -E "$pattern" | sed -E 's/^<!-- Build ID: ([0-9a-f]{12}) -->$/\1/')"
  [ "$(printf '%s\n' "$recorded" | grep -c .)" = 1 ] || return 1
  computed="$(root_lines "$1" | grep -vE "$pattern" | awk '{ if (n++) printf "\n"; printf "%s", $0 }' | sha256 | cut -c1-12)"
  [ "$recorded" = "$computed" ]
}

sha256() {
  if command -v sha256sum >/dev/null 2>&1; then sha256sum | awk '{print $1}'; else shasum -a 256 | awk '{print $1}'; fi
}

edited_generated_roots() {
  local home="$1" root
  for root in $COMPILED_ROOTS; do
    if [ -f "$home/$root" ] && has_marker "$home/$root" && ! has_valid_build_id "$home/$root"; then
      printf '%s\n' "$home/$root"
    fi
  done
}

parse_options() {
  HOME_DIR="" SOURCE_REF="" WORKSPACE_ONLY=0 REAL_HOME=0 BACKUP_DIR="" STAMP="" REHEARSAL="" MIGRATE=0
  while [ $# -gt 0 ]; do
    case "$1" in
      --home) [ $# -ge 2 ] || fail "--home needs a value"; HOME_DIR="$2"; shift 2 ;;
      --real-home) REAL_HOME=1; shift ;;
      --backup-dir) [ $# -ge 2 ] || fail "--backup-dir needs a value"; BACKUP_DIR="$2"; shift 2 ;;
      --source-ref) [ $# -ge 2 ] || fail "--source-ref needs a value"; SOURCE_REF="$2"; shift 2 ;;
      --stamp) [ $# -ge 2 ] || fail "--stamp needs a value"; STAMP="$2"; shift 2 ;;
      --rehearsal) [ $# -ge 2 ] || fail "--rehearsal needs a value"; REHEARSAL="$2"; shift 2 ;;
      --migrate) MIGRATE=1; shift ;;
      --workspace-only) WORKSPACE_ONLY=1; shift ;;
      *) fail "unknown option: $1" ;;
    esac
  done
}

cmd_render() {
  parse_options "$@"
  [ -n "$SOURCE_REF" ] || fail "render needs --source-ref"
  render_manifest "$(resolve_source_sha "$SOURCE_REF")" "$WORKSPACE_ONLY"
}

cmd_plan() {
  parse_options "$@"
  local sha
  sha="$(resolve_source_sha "${SOURCE_REF:-HEAD}")"
  printf '# Source: %s at %s\n' "$SOURCE_URL" "$sha"
  if [ -z "$(git -C "$REPO_ROOT" branch -r --contains "$sha" 2>/dev/null)" ]; then
    printf '# Warning: no remote branch contains %s yet; apm cannot fetch it until it is pushed.\n' "$sha"
  fi
  printf '# Consumer manifest (written to <HOME>/.apm/apm.yml by apply):\n\n'
  render_manifest "$sha" "$WORKSPACE_ONLY"
  cat <<EOF

# apply --home <disposable HOME> --source-ref $sha would run:
#   1. stop if an APM-generated root there was edited after compile ($COMPILED_ROOTS), or if a symlink or hard link
#      inside that HOME reaches outside it
#   2. stop if <HOME>/.apm/config.json holds more than default_client and prefer_ssh; keep a differing
#      <HOME>/.apm/apm.yml as apm.yml.<UTC>.bak
#   3. write the manifest above
#   4. apm install -g --only apm, from an empty environment plus HOME, PATH, locale, git config locations and a
#      TMPDIR in HOME; MCP servers stay as they are
#   5. apm compile -g --clean, the same way
# apply --real-home is blocked. The real HOME is switched by migrate --real-home --source-ref $sha --rehearsal <dir>, which
# needs a clean rehearse --migrate of a backup of that HOME first and would run:
#   1. stop if <HOME>/.apm is a checkout (.git or catalog/) or this repository lies inside it
#   2. stop unless the rehearsal's result.txt is mode=migrate, for the same HOME and ref, with no failed step, no lost
#      file other than a .apm-pin, and no skipped baseline; then the guards of apply, over the paths apm writes
#   3. record the sha256 of ${MIGRATE_UNTOUCHED_FILES// /, }; save the agmsg links
#   4. write the manifest above, move $MIGRATE_ROOTS
#      to <root>.bak-<UTC> (nothing is deleted)
#   5. apm install -g --only apm, apm compile -g --clean, then copy back the top-level entries apm did not deploy
#      (a link that leaves its root is copied; a broken link fails); restore the agmsg links; compare the sha256
#   6. on any failure, undo step 4 (migrate-rollback --stamp <UTC> does the same later). It prints the stamp.
# Not deployed by APM, and left to the manual steps in docs/native-distribution.md: agmsg db/teams links,
# catalog/rules and catalog/claude/rules, private skills, OpenCode and Pi instructions, host-local MCP.
# This plan wrote nothing.
EOF
}

# backup and rehearse: --home names a disposable HOME, --real-home the account's own. Exactly one of them.
target_home() {
  if [ "$REAL_HOME" = 1 ]; then
    [ -z "$HOME_DIR" ] || fail "pass either --home or --real-home, not both"
    account_home
  else
    [ -n "$HOME_DIR" ] || fail "$1 needs --home <disposable HOME>, or --real-home for the account's HOME"
    assert_disposable_home "$HOME_DIR"
  fi
}

cmd_apply() {
  parse_options "$@"
  [ "$REAL_HOME" = 0 ] || fail "applying to the real HOME is blocked: apm install deletes skills the old writer deployed. migrate is the only command that writes the real HOME, after a clean rehearse --migrate (docs/native-distribution.md)."
  [ -n "$SOURCE_REF" ] || fail "apply needs --source-ref; deploying never moves a pin on its own"
  [ -n "$HOME_DIR" ] || fail "apply needs --home <disposable HOME>"
  local home sha edited links
  home="$(assert_disposable_home "$HOME_DIR")"
  sha="$(resolve_source_sha "$SOURCE_REF")"
  assert_default_apm_config "$home"
  edited="$(edited_generated_roots "$home")"
  [ -z "$edited" ] || fail "these roots keep APM's marker but were edited after compile, and apm compile would overwrite them:
$edited
Delete the marker line to keep the file as hand-written, or move it aside, then re-run."

  links="$(shared_entries "$home")"
  [ -z "$links" ] || fail "these entries inside $home may share their data with files outside it, so writing them would change those files:
$links
Move them aside or make them plain directories and files of this HOME."

  install_manifest "$home" "$(render_manifest "$sha" "$WORKSPACE_ONLY")"

  run_apm "$home" install -g --only apm
  run_apm "$home" compile -g --clean
}

install_manifest() {
  local home="$1" manifest="$2" tmp
  mkdir -p "$home/.apm"
  # A new file renamed into place, so a hard link at apm.yml keeps the other file's contents.
  tmp="$(mktemp "$home/.apm/.apm.yml.XXXXXX")"
  printf '%s\n' "$manifest" >"$tmp"
  if [ -f "$home/.apm/apm.yml" ] && ! cmp -s "$tmp" "$home/.apm/apm.yml"; then
    keep_previous_manifest "$home"
  fi
  mv -f "$tmp" "$home/.apm/apm.yml"
}

keep_previous_manifest() {
  local home="$1" stamp bak n=1
  stamp="$(date -u +%Y%m%dT%H%M%SZ)"
  bak="$home/.apm/apm.yml.$stamp.bak"
  while [ -e "$bak" ] || [ -L "$bak" ]; do
    bak="$home/.apm/apm.yml.$stamp.$n.bak"
    n=$((n + 1))
  done
  cp -p "$home/.apm/apm.yml" "$bak"
  log "kept the previous manifest as $bak"
}

assert_backup_dir_outside_targets() {
  local home="$1" dir="$2" surface
  for surface in .apm .claude .codex .cursor .agents; do
    case "$dir/" in
      "$home/$surface/"*) fail "--backup-dir $dir must not be inside $home/$surface" ;;
    esac
  done
}

cmd_backup() {
  parse_options "$@"
  [ -n "$BACKUP_DIR" ] || fail "backup needs --backup-dir <new directory>"
  local home dir path
  home="$(target_home backup)"
  dir="$(physical_path "$BACKUP_DIR")"
  assert_backup_dir_outside_targets "$home" "$dir"
  if [ -e "$dir" ] && [ -n "$(ls -A "$dir")" ]; then fail "--backup-dir $dir already has files; backups are never overwritten"; fi
  mkdir -p "$dir/home"
  : >"$dir/present.txt"
  : >"$dir/absent.txt"
  for path in $BACKUP_PATHS; do
    if [ -e "$home/$path" ] || [ -L "$home/$path" ]; then
      mkdir -p "$(dirname "$dir/home/$path")"
      clone_copy "$home/$path" "$dir/home/$path"
      printf '%s\n' "$path" >>"$dir/present.txt"
    else
      printf '%s\n' "$path" >>"$dir/absent.txt"
    fi
  done
  if [ -d "$home/.local/state/agmsg" ]; then clone_copy "$home/.local/state/agmsg" "$dir/agmsg-state"; fi
  printf 'home=%s\ncreated=%s\n' "$home" "$(date -u +%Y-%m-%dT%H:%M:%SZ)" >"$dir/complete"
  log "backed up $(wc -l <"$dir/present.txt" | tr -d ' ') paths of $home into $dir"
}

# APFS clones on macOS; a plain copy elsewhere. Symlinks stay symlinks.
clone_copy() {
  cp -cpR "$1" "$2" 2>/dev/null || cp -pR "$1" "$2"
}

assert_completed_backup() {
  local home="$1"
  [ -n "$BACKUP_DIR" ] || fail "rehearse needs --backup-dir <a completed backup of this HOME>; run backup first"
  [ -f "$BACKUP_DIR/complete" ] || fail "$BACKUP_DIR is not a completed backup"
  grep -qxF "home=$home" "$BACKUP_DIR/complete" || fail "$BACKUP_DIR is a backup of another HOME"
}

# Every symlink of the scratch HOME ends up inside it, so nothing apm writes there reaches the real files.
isolate_scratch_links() {
  local home="$1" scratch="$2" link target resolved orig
  local store="$home/.local/state/agmsg/"
  while IFS= read -r link; do
    target="$(readlink "$link")"
    case "$target" in
      "$store"*)
        rm -f "$link"
        ln -s "$scratch/.local/state/agmsg/${target#"$store"}" "$link"
        ;;
      *)
        if [ ! -e "$link" ] || ! resolved="$(realpath "$link" 2>/dev/null)"; then
          # A relative link can point at a file of the HOME that the backup did not copy; resolve it in the HOME.
          orig="$home${link#"$scratch"}"
          if [ -e "$orig" ] && resolved="$(realpath "$orig" 2>/dev/null)"; then
            rm -f "$link"
            cp -cpRL "$resolved" "$link" 2>/dev/null || cp -pRL "$resolved" "$link" ||
              fail "cannot reproduce $orig -> $target in the scratch HOME"
            continue
          fi
          rm -f "$link"
          log "removed the broken link $link -> $target from the scratch HOME"
          continue
        fi
        case "$resolved/" in
          "$scratch/"*) ;;
          *)
            rm -f "$link"
            cp -cpRL "$resolved" "$link" 2>/dev/null || {
              rm -rf "$link"
              cp -pRL "$resolved" "$link"
            }
            ;;
        esac
        ;;
    esac
  done < <(find "$scratch" -type l | LC_ALL=C sort)
}

rehearsal_snapshot() {
  local scratch="$1" present="$2" path
  (cd "$scratch" && while IFS= read -r path; do
    [ -n "$path" ] || continue
    if [ -e "$path" ] || [ -L "$path" ]; then find "$path"; fi
  done <"$present" | LC_ALL=C sort)
}

agmsg_state() {
  env -u XDG_STATE_HOME HOME="$1" bash "$REPO_ROOT/scripts/agmsg-state.sh" "$2" >&2
}

assert_stamp() {
  [[ "$1" =~ ^[0-9]{8}T[0-9]{6}Z$ ]] || fail "--stamp must be a UTC stamp such as 20261109T120000Z"
}

migrate_record() {
  printf '%s/.apm/native-migrate-%s.txt\n' "$1" "$2"
}

# Moves each of MIGRATE_ROOTS to <root>.bak-<stamp> and records what it did in <HOME>/.apm/native-migrate-<stamp>.txt.
# Nothing is deleted. A root that does not exist is recorded as absent; a backup name already taken fails before any move.
migrate_roots() {
  local home="$1" stamp="$2" root record
  record="$(migrate_record "$home" "$stamp")"
  [ ! -e "$record" ] || fail "$record already exists; pick another stamp. Nothing was moved."
  for root in $MIGRATE_ROOTS; do
    if [ -e "$home/$root.bak-$stamp" ] || [ -L "$home/$root.bak-$stamp" ]; then
      fail "$home/$root.bak-$stamp already exists. Nothing was moved."
    fi
  done
  mkdir -p "$home/.apm"
  : >"$record"
  for root in $MIGRATE_ROOTS; do
    if [ -e "$home/$root" ] || [ -L "$home/$root" ]; then
      mv "$home/$root" "$home/$root.bak-$stamp" || fail "cannot move $home/$root aside"
      printf 'moved\t%s\n' "$root" >>"$record"
      log "moved $home/$root to $home/$root.bak-$stamp"
    else
      printf 'absent\t%s\n' "$root" >>"$record"
      log "$home/$root does not exist; nothing to move"
    fi
  done
}

# inside: the link stays a link (it points into the root); outside: its content is copied; broken: reinstate fails.
link_scope() {
  local home="$1" root="$2" bak="$3" entry="$4" target rest resolved bakp
  target="$(readlink "$entry")"
  case "$target" in
    "$home/$root")
      echo inside
      return
      ;;
    "$home/$root/"*)
      rest="${target#"$home/$root/"}"
      if [ -e "$bak/$rest" ] || [ -e "$home/$root/$rest" ]; then echo inside; else echo broken; fi
      return
      ;;
  esac
  if [ ! -e "$entry" ] || ! resolved="$(realpath "$entry" 2>/dev/null)"; then
    echo broken
    return
  fi
  bakp="$(cd "$bak" && pwd -P)"
  case "$resolved/" in
    "$bakp/"*) echo inside ;;
    *) echo outside ;;
  esac
}

# Puts back the top-level entries of each <root>.bak-<stamp> that the root lacks now (apm did not deploy them). An entry
# that exists is left alone. A link that leaves its root is copied, so nothing in the HOME depends on the place it
# pointed at; a broken link fails the whole step before anything is copied.
reinstate_entries() {
  local home="$1" stamp="$2" root bak entry name scope found=0 broken="" plan=""
  for root in $MIGRATE_ROOTS; do
    bak="$home/$root.bak-$stamp"
    if [ ! -e "$bak" ] && [ ! -L "$bak" ]; then continue; fi
    found=1
    while IFS= read -r -d '' entry; do
      name="$(basename "$entry")"
      if [ -e "$home/$root/$name" ] || [ -L "$home/$root/$name" ]; then continue; fi
      scope=plain
      if [ -L "$entry" ]; then scope="$(link_scope "$home" "$root" "$bak" "$entry")"; fi
      if [ "$scope" = broken ]; then
        broken="$broken  $entry -> $(readlink "$entry")"$'\n'
      else
        plan="$plan$root"$'\t'"$name"$'\t'"$scope"$'\n'
      fi
    done < <(find -H "$bak" -mindepth 1 -maxdepth 1 -print0)
  done
  [ "$found" = 1 ] || fail "no <root>.bak-$stamp of $MIGRATE_ROOTS exists in $home"
  [ -z "$broken" ] || fail "these entries are broken links, so they cannot be put back; nothing was copied:
$broken"
  while IFS=$'\t' read -r root name scope; do
    [ -n "$root" ] || continue
    mkdir -p "$home/$root" || fail "cannot create $home/$root"
    bak="$home/$root.bak-$stamp"
    if [ "$scope" = outside ]; then
      cp -cpRL "$bak/$name" "$home/$root/$name" 2>/dev/null || {
        rm -rf "${home:?}/$root/$name"
        cp -pRL "$bak/$name" "$home/$root/$name" || fail "cannot copy $bak/$name"
      }
    else
      clone_copy "$bak/$name" "$home/$root/$name" || fail "cannot copy $bak/$name"
    fi
    log "reinstated $root/$name ($scope)"
  done <<<"$plan"
}

# Moves the current roots to <root>.native-<stamp> and each <root>.bak-<stamp> back. Nothing is deleted, and a name already
# taken fails before any move.
rollback_roots() {
  local home="$1" stamp="$2" record kind root current
  record="$(migrate_record "$home" "$stamp")"
  [ -f "$record" ] || fail "$record does not exist; nothing to roll back"
  while IFS=$'\t' read -r kind root; do
    [ -n "$kind" ] || continue
    current="$home/$root"
    case "$kind" in
      moved)
        if [ ! -e "$current.bak-$stamp" ] && [ ! -L "$current.bak-$stamp" ]; then
          fail "$current.bak-$stamp is missing. Nothing was changed."
        fi
        ;;
      absent) ;;
      *) fail "$record holds an unknown line: $kind $root" ;;
    esac
    if { [ -e "$current" ] || [ -L "$current" ]; } && { [ -e "$current.native-$stamp" ] || [ -L "$current.native-$stamp" ]; }; then
      fail "$current.native-$stamp already exists. Nothing was changed."
    fi
  done <"$record"
  while IFS=$'\t' read -r kind root; do
    [ -n "$kind" ] || continue
    current="$home/$root"
    if [ -e "$current" ] || [ -L "$current" ]; then
      mv "$current" "$current.native-$stamp" || fail "cannot move $current aside"
      log "moved $current to $current.native-$stamp"
    fi
    if [ "$kind" = moved ]; then
      mv "$current.bak-$stamp" "$current" || fail "cannot move $current.bak-$stamp back"
      log "moved $current.bak-$stamp back to $current"
    fi
  done <"$record"
}

restore_agmsg_links() {
  local home="$1"
  if [ -L "$home/.agents/skills/agmsg/db" ] || [ -L "$home/.agents/skills/agmsg/teams" ]; then
    agmsg_state "$home" restore
  fi
}

# The reason a lost path (relative to HOME) is no loss, or nothing. Every entry is a full path under one of MIGRATE_ROOTS,
# except the .apm-pin basename rule; docs/native-distribution.md lists them. Anything else counts as lost.
allowed_lost_reason() {
  local path="$1" root
  case "$path" in
    .agents/skills/agmsg/run | .agents/skills/agmsg/run/*)
      echo "agmsg runtime state; the old path rebuilt the agmsg directory too, and apm replaces it"
      return
      ;;
    .agents/skills/agmsg/apm.yml | .claude/skills/agmsg/apm.yml | \
      .agents/skills/agmsg/.apm | .claude/skills/agmsg/.apm | \
      .agents/skills/agmsg/.apm/.plugin-skill-sources.json | .claude/skills/agmsg/.apm/.plugin-skill-sources.json)
      echo "metadata the old path's stage wrote; the agmsg scripts do not read it"
      return
      ;;
  esac
  if [ "$(basename "$path")" = .apm-pin ]; then
    for root in $MIGRATE_ROOTS; do
      case "$path" in
        "$root/"*)
          echo "pin marker inside a root that migrate moved aside"
          return
          ;;
      esac
    done
  fi
}

# Tab-separated <path> <reason> for each lost path that is no loss.
allowed_lost_paths() {
  local path reason
  while IFS= read -r path; do
    reason="$(allowed_lost_reason "$path")"
    if [ -n "$reason" ]; then printf '%s\t%s\n' "$path" "$reason"; fi
  done <"$1"
}

# apm 0.35.0 deletes deployed files it considers stale and `apm install --dry-run` does not preview that, so the same
# install and compile run on a clone of the backup first and the files that disappeared are counted.
cmd_rehearse() {
  parse_options "$@"
  [ -n "$SOURCE_REF" ] || fail "rehearse needs --source-ref"
  local home sha dir rehearsal scratch path manifest shared lost stamp mode=plain
  local install_status=0 compile_status=skipped agmsg_status=0 linked=0 reinstate_status=skipped allowed_lost=0 baseline_skips=0
  home="$(target_home rehearse)"
  assert_default_apm_config "$home"
  assert_completed_backup "$home"
  sha="$(resolve_source_sha "$SOURCE_REF")"
  dir="$(cd "$BACKUP_DIR" && pwd -P)"
  rehearsal="$(mktemp -d "$dir/rehearsal-$(date -u +%Y%m%dT%H%M%SZ).XXXXXX")"
  scratch="$rehearsal/home"
  mkdir "$scratch"
  : >"$rehearsal/apm.log"

  while IFS= read -r path; do
    [ -n "$path" ] || continue
    mkdir -p "$(dirname "$scratch/$path")"
    clone_copy "$dir/home/$path" "$scratch/$path"
  done <"$dir/present.txt"
  if [ -e "$home/.apm/apm_modules" ] || [ -L "$home/.apm/apm_modules" ]; then
    mkdir -p "$scratch/.apm"
    clone_copy "$home/.apm/apm_modules" "$scratch/.apm/apm_modules"
  fi
  if [ -d "$dir/agmsg-state" ]; then
    mkdir -p "$scratch/.local/state"
    clone_copy "$dir/agmsg-state" "$scratch/.local/state/agmsg"
  fi
  assert_default_apm_config "$scratch"
  isolate_scratch_links "$home" "$scratch"
  shared="$(shared_entries "$scratch")"
  [ -z "$shared" ] || fail "the scratch HOME $scratch still shares data with files outside it:
$shared"

  rehearsal_snapshot "$scratch" "$dir/present.txt" >"$rehearsal/before.txt"
  manifest="$(render_manifest "$sha" "$WORKSPACE_ONLY")"
  mkdir -p "$scratch/.apm"
  rm -f "$scratch/.apm/apm.yml"
  printf '%s\n' "$manifest" >"$scratch/.apm/apm.yml"

  if [ -L "$scratch/.agents/skills/agmsg/db" ]; then
    linked=1
    agmsg_state "$scratch" save
  fi
  if [ "$MIGRATE" = 1 ]; then
    mode=migrate
    stamp="$(date -u +%Y%m%dT%H%M%SZ)"
    migrate_roots "$scratch" "$stamp"
  fi
  run_apm "$scratch" install -g --only apm 2>&1 | tee -a "$rehearsal/apm.log" >&2 || install_status=$?
  if [ "$install_status" -eq 0 ]; then
    compile_status=0
    run_apm "$scratch" compile -g --clean 2>&1 | tee -a "$rehearsal/apm.log" >&2 || compile_status=$?
  fi
  if [ "$MIGRATE" = 1 ] && [ "$install_status" = 0 ] && [ "$compile_status" = 0 ]; then
    reinstate_status=0
    (reinstate_entries "$scratch" "$stamp") || reinstate_status=$?
  fi
  if [ "$linked" = 1 ]; then agmsg_state "$scratch" restore || agmsg_status=1; fi
  baseline_skips="$(grep -c 'no trustworthy local deployment baseline' "$rehearsal/apm.log" || true)"

  rehearsal_snapshot "$scratch" "$dir/present.txt" >"$rehearsal/after.txt"
  LC_ALL=C comm -23 "$rehearsal/before.txt" "$rehearsal/after.txt" >"$rehearsal/lost-all.txt"
  if [ "$MIGRATE" = 1 ]; then
    allowed_lost_paths "$rehearsal/lost-all.txt" >"$rehearsal/allowed-lost.txt"
    LC_ALL=C comm -23 "$rehearsal/lost-all.txt" <(cut -f1 "$rehearsal/allowed-lost.txt") >"$rehearsal/lost.txt"
    allowed_lost="$(wc -l <"$rehearsal/allowed-lost.txt" | tr -d ' ')"
  else
    cp "$rehearsal/lost-all.txt" "$rehearsal/lost.txt"
  fi
  lost="$(wc -l <"$rehearsal/lost.txt" | tr -d ' ')"
  printf 'mode=%s\nhome=%s\nsource_ref=%s\nworkspace_only=%s\ninstall_status=%s\ncompile_status=%s\nreinstate_status=%s\nagmsg_status=%s\nlost=%s\nallowed_lost=%s\nbaseline_skips=%s\n' \
    "$mode" "$home" "$sha" "$WORKSPACE_ONLY" "$install_status" "$compile_status" "$reinstate_status" "$agmsg_status" "$lost" "$allowed_lost" "$baseline_skips" \
    >"$rehearsal/result.txt"

  if [ "$install_status" = 0 ] && [ "$compile_status" = 0 ] && [ "$agmsg_status" = 0 ] && [ "$lost" = 0 ] &&
    { [ "$MIGRATE" = 0 ] || { [ "$reinstate_status" = 0 ] && [ "$baseline_skips" = 0 ]; }; }; then
    log "rehearsal clean ($mode): install and compile ran on a clone of $dir and lost no file ($rehearsal)"
    return 0
  fi
  log "rehearsal failed ($mode): install=$install_status compile=$compile_status reinstate=$reinstate_status agmsg=$agmsg_status lost=$lost baseline_skips=$baseline_skips ($rehearsal/result.txt)"
  if [ "$lost" != 0 ]; then
    log "files that disappeared, all in $rehearsal/lost.txt:"
    head -n 20 "$rehearsal/lost.txt" | sed 's/^/  /' >&2
  fi
  exit 1
}

home_flags() {
  if [ "$REAL_HOME" = 1 ]; then printf '%s' "--real-home"; else printf '%s' "--home $1"; fi
}

cmd_reinstate() {
  parse_options "$@"
  [ -n "$STAMP" ] || fail "reinstate needs --stamp <UTC stamp of the migrate>"
  assert_stamp "$STAMP"
  local home
  home="$(target_home reinstate)"
  reinstate_entries "$home" "$STAMP"
}

assert_not_checkout() {
  local home="$1" repo
  if [ -e "$home/.apm/.git" ] || [ -L "$home/.apm/.git" ] || [ -e "$home/.apm/catalog" ] || [ -L "$home/.apm/catalog" ]; then
    fail "$home/.apm is an authoring checkout (.git or catalog/), and apm writes its manifest and lock there. Move the checkout out of $home/.apm first (docs/native-distribution.md)."
  fi
  repo="$(physical_path "$REPO_ROOT")"
  case "$repo/" in
    "$(physical_path "$home/.apm")/"*) fail "this repository ($repo) is inside $home/.apm, the directory migrate writes" ;;
  esac
}

result_has() {
  grep -qxF "$2" "$1/result.txt"
}

assert_migrate_rehearsal() {
  local home="$1" sha="$2" dir="$3" want
  [ -f "$dir/result.txt" ] || fail "--rehearsal $dir has no result.txt; run rehearse --migrate and pass its rehearsal-<UTC> directory"
  for want in mode=migrate "home=$home" "source_ref=$sha" "workspace_only=$WORKSPACE_ONLY" install_status=0 compile_status=0 \
    reinstate_status=0 agmsg_status=0 lost=0 baseline_skips=0; do
    result_has "$dir" "$want" || fail "the rehearsal $dir does not show $want; run rehearse --migrate again for this HOME, --source-ref and --workspace-only until it is clean"
  done
}

untouched_hashes() {
  local home="$1" path
  for path in $MIGRATE_UNTOUCHED_FILES; do
    if [ -f "$home/$path" ]; then printf '%s %s\n' "$path" "$(sha256 <"$home/$path")"; else printf '%s absent\n' "$path"; fi
  done
}

# Runs from the EXIT trap of cmd_migrate once the roots may have moved: undo the move, keep every file, keep the exit status.
migrate_failure() {
  local status=$?
  trap - EXIT
  log "migrate failed (exit $status)"
  if [ -f "$(migrate_record "$MIGRATE_HOME" "$MIGRATE_STAMP")" ]; then
    log "rolling the roots back"
    (rollback_roots "$MIGRATE_HOME" "$MIGRATE_STAMP") || log "the automatic rollback failed; fix the cause, then run migrate-rollback --stamp $MIGRATE_STAMP"
    if [ "$MIGRATE_AGMSG_LINKED" = 1 ]; then
      agmsg_state "$MIGRATE_HOME" restore || log "the agmsg links were not restored; run mise run agmsg:state:restore"
    fi
  fi
  exit "$status"
}

cmd_migrate() {
  parse_options "$@"
  [ -n "$SOURCE_REF" ] || fail "migrate needs --source-ref; deploying never moves a pin on its own"
  [ -n "$REHEARSAL" ] || fail "migrate needs --rehearsal <the rehearsal-<UTC> directory of a clean rehearse --migrate>"
  local home sha edited links manifest before after
  home="$(target_home migrate)"
  sha="$(resolve_source_sha "$SOURCE_REF")"
  assert_not_checkout "$home"
  assert_migrate_rehearsal "$home" "$sha" "$(cd "$REHEARSAL" 2>/dev/null && pwd -P || printf '%s' "$REHEARSAL")"

  assert_default_apm_config "$home"
  edited="$(edited_generated_roots "$home")"
  [ -z "$edited" ] || fail "these roots keep APM's marker but were edited after compile, and apm compile would overwrite them:
$edited
Delete the marker line to keep the file as hand-written, or move it aside, then re-run."
  if [ "$REAL_HOME" = 1 ]; then links="$(real_home_shared_entries "$home")"; else links="$(shared_entries "$home")"; fi
  [ -z "$links" ] || fail "these entries of $home may share their data with files outside it, so writing them would change those files:
$links
Move them aside or make them plain directories and files of this HOME."

  manifest="$(render_manifest "$sha" "$WORKSPACE_ONLY")"
  before="$(untouched_hashes "$home")"
  MIGRATE_AGMSG_LINKED=0
  if [ -L "$home/.agents/skills/agmsg/db" ]; then
    MIGRATE_AGMSG_LINKED=1
    agmsg_state "$home" save
  fi

  MIGRATE_HOME="$home" MIGRATE_STAMP="$(date -u +%Y%m%dT%H%M%SZ)"
  install_manifest "$home" "$manifest"
  trap migrate_failure EXIT
  migrate_roots "$home" "$MIGRATE_STAMP"
  run_apm "$home" install -g --only apm
  run_apm "$home" compile -g --clean
  reinstate_entries "$home" "$MIGRATE_STAMP"
  if [ "$MIGRATE_AGMSG_LINKED" = 1 ]; then agmsg_state "$home" restore; fi
  after="$(untouched_hashes "$home")"
  [ "$after" = "$before" ] || fail "the sha256 of $MIGRATE_UNTOUCHED_FILES changed during migrate:
before: $(printf '%s' "$before" | tr '\n' ' ')
after: $(printf '%s' "$after" | tr '\n' ' ')"
  trap - EXIT

  log "migrated $home; the previous roots are kept as <root>.bak-$MIGRATE_STAMP (record: $(migrate_record "$home" "$MIGRATE_STAMP"))"
  log "to undo: mise run native:migrate-rollback -- $(home_flags "$home") --stamp $MIGRATE_STAMP"
  printf '%s\n' "$MIGRATE_STAMP"
}

cmd_migrate_rollback() {
  parse_options "$@"
  [ -n "$STAMP" ] || fail "migrate-rollback needs --stamp <UTC stamp of the migrate>"
  assert_stamp "$STAMP"
  local home
  home="$(target_home migrate-rollback)"
  rollback_roots "$home" "$STAMP"
  restore_agmsg_links "$home"
  log "rolled $home back to the roots of $STAMP; the roots native wrote are kept as <root>.native-$STAMP"
}

# APM picks cache, config and temp locations from more than HOME (APM_CACHE_DIR, XDG_*, TMPDIR), and git honours
# tokens, proxies and askpass from the environment, so apm starts from an empty environment plus this allowlist, with
# its temp directory inside HOME.
# ssh splits UserKnownHostsFile on whitespace and reads quotes and backslashes, so a HOME holding them would send
# new host keys to a path outside it.
assert_ssh_safe_home() {
  case "$1" in
    *[[:space:]\"\\]*) fail "$1 contains whitespace, a quote or a backslash, which ssh would split into another path" ;;
  esac
}

run_apm() {
  local home="$1" var
  shift
  assert_ssh_safe_home "$home"
  mkdir -p "$home/.cache/apm-native-tmp"
  # ssh takes its config and known_hosts from the account HOME, not $HOME; new host keys go to the target HOME.
  mkdir -p "$home/.ssh"
  local ssh_cmd
  ssh_cmd="ssh -F /dev/null -o $(printf '%q' "UserKnownHostsFile=$home/.ssh/known_hosts \"$(user_db_home)/.ssh/known_hosts\"")"
  local env_args=(HOME="$home" PATH="$PATH" TMPDIR="$home/.cache/apm-native-tmp" LANG="${LANG:-C.UTF-8}" GIT_SSH_COMMAND="$ssh_cmd")
  for var in LC_ALL TERM PYTHONUTF8 GIT_CONFIG_GLOBAL GIT_CONFIG_NOSYSTEM GIT_CEILING_DIRECTORIES; do
    if [ -n "${!var:-}" ]; then env_args+=("$var=${!var}"); fi
  done
  (cd "$home" && env -i "${env_args[@]}" "$APM_BIN" "$@")
}

# Anything apm could write through to a file outside HOME: a symlink in HOME that resolves outside it (or is broken),
# and a regular file there with another hard link.
shared_entries() {
  shared_entries_in "$1" "$1"
}

# The same test over the given paths of HOME only.
shared_entries_in() {
  local home="$1" path
  shift
  for path in "$@"; do
    [ -e "$path" ] || [ -L "$path" ] || continue
    find "$path" -type l | LC_ALL=C sort | while IFS= read -r link; do
      escaping_link_line "$home" "$link"
    done
    find "$path" -type f -links +1 | LC_ALL=C sort | sed 's/^/  /; s/$/ (hard link)/'
  done
}

escaping_link_line() {
  local home="$1" link="$2" target
  # GNU realpath resolves a link whose last component is missing, so test the target first.
  if [ ! -e "$link" ] || ! target="$(realpath "$link" 2>/dev/null)"; then
    printf '  %s (broken)\n' "$link"
    return
  fi
  case "$target/" in
    "$home/"*) ;;
    *) printf '  %s -> %s\n' "$link" "$target" ;;
  esac
}

# migrate --real-home: the paths apm writes (REAL_HOME_WRITE_PATHS), and the tool directories above them only when they
# are links themselves, so the rest of the HOME is not walked.
real_home_shared_entries() {
  local home="$1" path
  for path in $REAL_HOME_TOOL_DIRS; do
    if [ -L "$home/$path" ]; then escaping_link_line "$home" "$home/$path"; fi
  done
  set --
  for path in $REAL_HOME_WRITE_PATHS; do set -- "$@" "$home/$path"; done
  shared_entries_in "$home" "$@"
}

# apm reads ~/.apm/config.json with json.load and takes temp_dir and other locations from it. Decode it the same way
# and allow only default_client and prefer_ssh, which move no write location.
assert_default_apm_config() {
  local config="$1/.apm/config.json" extra
  [ -e "$config" ] || return 0
  extra="$(python3 -c 'import json, sys; print(" ".join(sorted(set(json.load(open(sys.argv[1], encoding="utf-8"))) - {"default_client", "prefer_ssh"})))' "$config")" ||
    fail "$config is not a JSON object apm could read"
  [ -z "$extra" ] || fail "$config sets $extra; only default_client and prefer_ssh may be set there"
}

main() {
  local command="${1:-plan}"
  [ $# -eq 0 ] || shift
  case "$command" in
    plan) cmd_plan "$@" ;;
    render) cmd_render "$@" ;;
    apply) cmd_apply "$@" ;;
    backup) cmd_backup "$@" ;;
    rehearse) cmd_rehearse "$@" ;;
    migrate) cmd_migrate "$@" ;;
    migrate-rollback) cmd_migrate_rollback "$@" ;;
    reinstate) cmd_reinstate "$@" ;;
    -h | --help | help) usage ;;
    *) usage >&2; exit 2 ;;
  esac
}

main "$@"
