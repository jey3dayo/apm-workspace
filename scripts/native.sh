#!/usr/bin/env bash
# Native APM distribution: a consumer manifest pins this repository's packages by commit SHA, and `apm install -g`
# followed by `apm compile -g --clean` deploy them. What APM does not deploy is listed in docs/native-distribution.md
# and stays with the existing manual helpers. sync orchestrates that documented workflow.
#
# apply targets a disposable HOME and refuses the account's real HOME, its ancestors and the tool state inside it.
# apply --real-home is blocked; migrate writes the real HOME after a clean `rehearse --migrate`, and migrate-rollback and
# reinstate undo or complete it (docs/native-distribution.md). backup and rehearse only read deployment data; all native
# operations share a persistent lock in .cache/apm-native-operation.lock, outside the caches migrate moves aside.
set -euo pipefail

SCRIPT_PATH="${BASH_SOURCE[0]}"
while [ -L "$SCRIPT_PATH" ]; do
  SCRIPT_DIR=$(CDPATH='' cd -P -- "$(dirname -- "$SCRIPT_PATH")" && pwd)
  LINK_TARGET=$(readlink "$SCRIPT_PATH")
  case "$LINK_TARGET" in
    /*) SCRIPT_PATH="$LINK_TARGET" ;;
    *) SCRIPT_PATH="$SCRIPT_DIR/$LINK_TARGET" ;;
  esac
done
SCRIPT_DIR=$(CDPATH='' cd -P -- "$(dirname -- "$SCRIPT_PATH")" && pwd)
REPO_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
APM_LIB_DIR="$SCRIPT_DIR/lib"
unset LINK_TARGET SCRIPT_PATH
ROOT_MANIFEST="$REPO_ROOT/apm.yml"
SOURCE_URL="${APM_NATIVE_SOURCE_URL:-https://github.com/jey3dayo/apm-workspace.git}"
APM_BIN="${APM_BIN:-apm}"
GENERATED_ROOT_MARKER="<!-- Generated by APM CLI from .apm/ primitives -->"
# Roots `apm compile -g` may write. An edited copy that kept APM's marker would be overwritten without notice.
COMPILED_ROOTS=".claude/CLAUDE.md .codex/AGENTS.md .cursor/AGENTS.md"
PROTECTED_SURFACES=".apm .claude .codex .cursor .agents .config .cache .local Library"
# Skills and agents roots the old writer filled. migrate moves them aside (never deletes) before apm install, then
# reinstate_entries puts back whatever apm did not deploy.
MIGRATE_ROOTS=".agents/skills .claude/skills .claude/agents .cursor/agents"
# What apm writes in the real HOME: the migrated roots, rules, the compiled roots, its own state and caches. migrate
# scans only these for links that leave the HOME.
REAL_HOME_WRITE_PATHS=".agents/skills .claude/skills .claude/agents .cursor/agents .claude/rules .claude/commands .codex/rules .cursor/rules
.claude/CLAUDE.md .codex/AGENTS.md .cursor/AGENTS.md .apm .cache/apm Library/Caches/apm"
REAL_HOME_TOOL_DIRS=".agents .claude .codex .cursor .cache Library Library/Caches"
# External dependencies that APM only accepts in the structured form (a Codex native plugin bundle is otherwise
# attempted): <manifest path>=<git repository>:<skill>. render turns `- <manifest path>#<40-hex SHA>` into
# `- git: <repository> / ref: <SHA> / skills: [<skill>]`.
EXTERNAL_PACKAGE_MAP="nanaism/yomiyasu/skills/yomiyasu=nanaism/yomiyasu:yomiyasu"
# Files whose content a migrate must leave byte for byte alone.
MIGRATE_UNTOUCHED_FILES=".codex/config.toml .claude/settings.json"
# Non-secret paths apply can change; backup copies them and rehearse reproduces them in a scratch HOME. Tool configs that
# may hold credentials (~/.codex/config.toml, MCP configs) are not here, which is why apply installs with --only apm.
BACKUP_PATHS=".apm/apm.yml .apm/config.json .apm/apm.lock.yaml .apm/deployment-receipts .claude/skills .claude/agents .claude/rules .claude/commands .claude/CLAUDE.md
.codex/AGENTS.md .codex/rules .cursor/agents .cursor/rules .cursor/AGENTS.md .agents/skills AGENTS.md .config/opencode/AGENTS.md"

. "$APM_LIB_DIR/shell-common.sh"
. "$APM_LIB_DIR/native-core.sh"
. "$APM_LIB_DIR/native-manifest.sh"
. "$APM_LIB_DIR/native-backup.sh"

# agmsg-state.sh restores the links under the default store (it runs without XDG_STATE_HOME), so a db or teams link that
# points anywhere else would be repointed at an empty default store, leaving the history behind.
assert_default_agmsg_store() {
  local home="$1" name target
  for name in db teams; do
    [ -L "$home/.agents/skills/agmsg/$name" ] || continue
    target="$(readlink "$home/.agents/skills/agmsg/$name")"
    [ "$target" = "$home/.local/state/agmsg/$name" ] ||
      fail "$home/.agents/skills/agmsg/$name points at $target, not at $home/.local/state/agmsg/$name, the only store agmsg-state.sh relinks to. Nothing was changed; move the data to the default store (or relink it) first."
  done
}

# The previous rendered manifest records whether it was rendered with --workspace-only; the previous lock lists packages
# only a full render deploys, so a change of mode would make every external package look dropped.
assert_same_render_mode() {
  local home="$1" previous
  [ -f "$home/.apm/apm.yml" ] || return 0
  previous="$(sed -n 's/^# native-render: workspace_only=\([01]\)$/\1/p' "$home/.apm/apm.yml" | head -n 1)"
  [ -z "$previous" ] || [ "$previous" = "$WORKSPACE_ONLY" ] ||
    fail "the previous manifest of $home was rendered with workspace_only=$previous, this run uses workspace_only=$WORKSPACE_ONLY; the previous lock would make every external package look dropped. Use the same mode."
}

# The links of the migrated roots that migrate would refuse: broken, or leading outside the HOME (escaping_link_line).
root_escaping_links() {
  local home="$1" root link
  for root in $MIGRATE_ROOTS; do
    [ -e "$home/$root" ] || [ -L "$home/$root" ] || continue
    find "$home/$root" -type l | LC_ALL=C sort | while IFS= read -r link; do
      escaping_link_line "$home" "$link"
    done
  done
}

# Every symlink of the scratch HOME ends up inside it, so nothing apm writes there reaches the real files.
isolate_scratch_links() {
  local home="$1" scratch="$2" link target resolved orig
  local store="$home/.local/state/agmsg/"
  while IFS= read -r link; do
    target="$(readlink "$link")"
    case "$target" in
      "$store"*)
        rm -f "$link"
        ln -s "$scratch/.local/state/agmsg/${target#"$store"}" "$link"
        ;;
      *)
        if [ ! -e "$link" ] || ! resolved="$(realpath "$link" 2>/dev/null)"; then
          # A relative link can point at a file of the HOME that the backup did not copy; resolve it in the HOME.
          orig="$home${link#"$scratch"}"
          if [ -e "$orig" ] && resolved="$(realpath "$orig" 2>/dev/null)"; then
            rm -f "$link"
            cp -cpRL "$resolved" "$link" 2>/dev/null || cp -pRL "$resolved" "$link" ||
              fail "cannot reproduce $orig -> $target in the scratch HOME"
            continue
          fi
          rm -f "$link"
          log "removed the broken link $link -> $target from the scratch HOME"
          continue
        fi
        case "$resolved/" in
          "$scratch/"*) ;;
          *)
            rm -f "$link"
            cp -cpRL "$resolved" "$link" 2>/dev/null || {
              rm -rf "$link"
              cp -pRL "$resolved" "$link"
            }
            ;;
        esac
        ;;
    esac
  done < <(find "$scratch" -type l | LC_ALL=C sort)
}

rehearsal_snapshot() {
  local scratch="$1" present="$2" path
  (cd "$scratch" && while IFS= read -r path; do
    [ -n "$path" ] || continue
    if [ -e "$path" ] || [ -L "$path" ]; then find "$path"; fi
  done <"$present" | LC_ALL=C sort)
}

agmsg_state() {
  env -u XDG_STATE_HOME HOME="$1" bash "$REPO_ROOT/scripts/agmsg-state.sh" "$2" >&2
}

assert_stamp() {
  [[ "$1" =~ ^[0-9]{8}T[0-9]{6}Z$ ]] || fail "--stamp must be a UTC stamp such as 20261109T120000Z"
}

migrate_record() {
  printf '%s/.apm/native-migrate-%s.txt\n' "$1" "$2"
}

# Creates the record exclusively (noclobber), so only the run that owns a stamp may move roots or roll them back; a second
# run that drew the same stamp stops here, before it sets the failure trap.
claim_migrate_record() {
  local home="$1" stamp="$2" record
  record="$(migrate_record "$home" "$stamp")"
  mkdir -p "$home/.apm"
  (set -o noclobber && : >"$record") 2>/dev/null || fail "$record already exists: another migrate drew the same stamp. Nothing was changed; run again."
}

migrate_deployed_record() {
  printf '%s/.apm/native-migrate-%s.deployed.txt\n' "$1" "$2"
}

# "<root><TAB><top-level entry>" for each entry of MIGRATE_ROOTS that the previous apm.lock.yaml of this HOME lists in a
# deployed_files list (the lock a native deployment left; there is none before the first migrate).
previous_deployed_entries() {
  local lock="$1/.apm/apm.lock.yaml"
  [ -f "$lock" ] || return 0
  awk -v roots="$MIGRATE_ROOTS" '
    BEGIN { n = split(roots, root, " ") }
    /^[[:space:]]*- / {
      line = $0
      sub(/^[[:space:]]*- /, "", line)
      gsub(/["\047]/, "", line)
      for (i = 1; i <= n; i++) {
        prefix = root[i] "/"
        if (index(line, prefix) != 1) continue
        rest = substr(line, length(prefix) + 1)
        sub(/\/.*/, "", rest)
        if (rest != "") print root[i] "\t" rest
      }
    }
  ' "$lock" | LC_ALL=C sort -u
}

# Moves each of MIGRATE_ROOTS to <root>.bak-<stamp> and records what it did in <HOME>/.apm/native-migrate-<stamp>.txt
# (claimed by claim_migrate_record first)
# (a "moved" line is written before the move and a "done" line after it, so a root without "done" may not have moved;
# rollback adds "restored" per root, so it can resume).
# Nothing is deleted. A root that does not exist is recorded as absent; a backup name already taken fails before any move.
migrate_roots() {
  local home="$1" stamp="$2" root record
  record="$(migrate_record "$home" "$stamp")"
  { [ -f "$record" ] && [ ! -s "$record" ]; } || fail "$record was not claimed (claim_migrate_record). Nothing was moved."
  for root in $MIGRATE_ROOTS; do
    if [ -e "$home/$root.bak-$stamp" ] || [ -L "$home/$root.bak-$stamp" ]; then
      fail "$home/$root.bak-$stamp already exists. Nothing was moved."
    fi
  done
  mkdir -p "$home/.apm"
  previous_deployed_entries "$home" >"$(migrate_deployed_record "$home" "$stamp")"
  for root in $MIGRATE_ROOTS; do
    if [ -e "$home/$root" ] || [ -L "$home/$root" ]; then
      printf 'moved\t%s\n' "$root" >>"$record"
      mv "$home/$root" "$home/$root.bak-$stamp" || fail "cannot move $home/$root aside"
      printf 'done\t%s\n' "$root" >>"$record"
      log "moved $home/$root to $home/$root.bak-$stamp"
    else
      printf 'absent\t%s\n' "$root" >>"$record"
      log "$home/$root does not exist; nothing to move"
    fi
  done
}

# inside: the link stays a link (it points into the root); outside: its content is copied; broken: reinstate fails.
link_scope() {
  local home="$1" root="$2" bak="$3" entry="$4" target rest resolved bakp
  target="$(readlink "$entry")"
  case "$target" in
    "$home/$root")
      echo inside
      return
      ;;
    "$home/$root/"*)
      rest="${target#"$home/$root/"}"
      if [ -e "$bak/$rest" ] || [ -e "$home/$root/$rest" ]; then echo inside; else echo broken; fi
      return
      ;;
  esac
  if [ ! -e "$entry" ] || ! resolved="$(realpath "$entry" 2>/dev/null)"; then
    echo broken
    return
  fi
  bakp="$(cd "$bak" && pwd -P)"
  case "$resolved/" in
    "$bakp/"*) echo inside ;;
    *) echo outside ;;
  esac
}

# Links among the directories reinstate writes into and copies from (the roots, their .bak-<stamp>, the tool directories
# above them and .apm, where the reports go) that leave the HOME or are broken: a copy through one would write outside it.
reinstate_escaping_links() {
  local home="$1" stamp="$2" root path
  for path in .agents .claude .cursor .apm; do
    if [ -L "$home/$path" ]; then escaping_link_line "$home" "$home/$path"; fi
  done
  for root in $MIGRATE_ROOTS; do
    for path in "$root" "$root.bak-$stamp"; do
      if [ -L "$home/$path" ]; then escaping_link_line "$home" "$home/$path"; fi
    done
  done
}

# True when the old entry differs in more than runtime state: agmsg's run/ db teams (agmsg-state.sh restores the links
# after this step) and the synced-skill cache that a running Claude Code recreates during migrate.
reinstate_differs() {
  case "$3" in
    .claude/skills/synced) return 1 ;;
    .agents/skills/agmsg) ! diff -rq -x .apm-pin -x run -x db -x teams "$1" "$2" >/dev/null 2>&1 ;;
    *) ! diff -rq -x .apm-pin "$1" "$2" >/dev/null 2>&1 ;;
  esac
}

# Puts back the top-level entries of each <root>.bak-<stamp> that the root lacks now (apm did not deploy them), except
# the entries the previous native lock listed as deployed (native-migrate-<stamp>.deployed.txt): those were not deployed this
# time. An entry that exists is left alone; one whose content differs from the old entry is listed in <report>skipped.txt. A link that leaves its root is
# copied, so nothing in the HOME depends on the place it pointed at; a broken link fails the whole step before anything
# is copied. <report>reinstated.txt lists what was put back.
reinstate_entries() {
  local home="$1" stamp="$2" report="${3:-}" root bak entry name scope found=0 broken="" plan="" escaping deployed skipped=""
  deployed="$(migrate_deployed_record "$home" "$stamp")"
  escaping="$(reinstate_escaping_links "$home" "$stamp")"
  [ -z "$escaping" ] || fail "these links of $home lead outside it or are broken, so copying into the roots would write outside the HOME; nothing was copied:
$escaping"
  for root in $MIGRATE_ROOTS; do
    bak="$home/$root.bak-$stamp"
    if [ ! -e "$bak" ] && [ ! -L "$bak" ]; then continue; fi
    found=1
    while IFS= read -r -d '' entry; do
      name="$(basename "$entry")"
      if [ -e "$home/$root/$name" ] || [ -L "$home/$root/$name" ]; then
        if reinstate_differs "$entry" "$home/$root/$name" "$root/$name"; then skipped="$skipped$root/$name"$'\n'; fi
        continue
      fi
      if [ -f "$deployed" ] && grep -qxF "$root"$'\t'"$name" "$deployed"; then continue; fi
      scope=plain
      if [ -L "$entry" ]; then scope="$(link_scope "$home" "$root" "$bak" "$entry")"; fi
      if [ "$scope" = broken ]; then
        broken="$broken  $entry -> $(readlink "$entry")"$'\n'
      else
        plan="$plan$root"$'\t'"$name"$'\t'"$scope"$'\n'
      fi
    done < <(find -H "$bak" -mindepth 1 -maxdepth 1 -print0)
  done
  [ "$found" = 1 ] || fail "no <root>.bak-$stamp of $MIGRATE_ROOTS exists in $home"
  [ -z "$broken" ] || fail "these entries are broken links, so they cannot be put back; nothing was copied:
$broken"
  if [ -n "$report" ]; then
    mkdir -p "$(dirname "${report}x")" || fail "cannot create the directory of ${report}"
    printf '%s' "$skipped" >"${report}skipped.txt"
    : >"${report}reinstated.txt"
    [ -z "$skipped" ] || log "warning: the entries of the old roots listed in ${report}skipped.txt share a name with what apm deployed, so they were not put back although their content differs from the old entry; if one is a private override of a catalog skill, put it back by hand"
  fi
  while IFS=$'\t' read -r root name scope; do
    [ -n "$root" ] || continue
    mkdir -p "$home/$root" || fail "cannot create $home/$root"
    bak="$home/$root.bak-$stamp"
    if [ "$scope" = outside ]; then
      cp -cpRL "$bak/$name" "$home/$root/$name" 2>/dev/null || {
        rm -rf "${home:?}/$root/$name"
        cp -pRL "$bak/$name" "$home/$root/$name" || fail "cannot copy $bak/$name"
      }
    else
      clone_copy "$bak/$name" "$home/$root/$name" || fail "cannot copy $bak/$name"
    fi
    log "reinstated $root/$name ($scope)"
    if [ -n "$report" ]; then printf '%s/%s\t%s\n' "$root" "$name" "$scope" >>"${report}reinstated.txt"; fi
  done <<<"$plan"
}

record_has() {
  grep -qxF "$1"$'\t'"$2" "$3"
}

# The state a rollback leaves when it stops between moving the backup back and writing "restored": the backup is gone, the
# root exists, and the root native wrote is kept beside it. A backup deleted by hand leaves no <root>.native-<stamp>.
restored_but_unrecorded() {
  { [ -e "$1" ] || [ -L "$1" ]; } && { [ -e "$1.native-$2" ] || [ -L "$1.native-$2" ]; }
}

# Moves the current roots to <root>.native-<stamp> and each <root>.bak-<stamp> back, and records "restored" per root, so a
# run that stopped part way is finished by running it again. Nothing is deleted, and a name already taken fails before any
# move. A root whose move never finished (no "done", no backup) is left as it is; a backup that is gone after "done"
# (deleted by hand) fails before any move.
rollback_roots() {
  local home="$1" stamp="$2" record kind root current lines
  record="$(migrate_record "$home" "$stamp")"
  [ -f "$record" ] || fail "$record does not exist; nothing to roll back"
  lines="$(cat "$record")"
  while IFS=$'\t' read -r kind root; do
    [ -n "$kind" ] || continue
    current="$home/$root"
    case "$kind" in
      moved)
        record_has restored "$root" "$record" && continue
        if [ ! -e "$current.bak-$stamp" ] && [ ! -L "$current.bak-$stamp" ] && record_has "done" "$root" "$record"; then
          restored_but_unrecorded "$current" "$stamp" && continue
          fail "$current.bak-$stamp is missing. Nothing was changed."
        fi
        ;;
      absent) record_has restored "$root" "$record" && continue ;;
      done | restored) continue ;;
      *) fail "$record holds an unknown line: $kind $root" ;;
    esac
    if { [ -e "$current" ] || [ -L "$current" ]; } && { [ -e "$current.native-$stamp" ] || [ -L "$current.native-$stamp" ]; }; then
      fail "$current.native-$stamp already exists. Nothing was changed."
    fi
  done <<<"$lines"
  while IFS=$'\t' read -r kind root; do
    case "$kind" in moved | absent) ;; *) continue ;; esac
    current="$home/$root"
    record_has restored "$root" "$record" && continue
    if [ "$kind" = moved ] && [ ! -e "$current.bak-$stamp" ] && [ ! -L "$current.bak-$stamp" ] && record_has "done" "$root" "$record" && restored_but_unrecorded "$current" "$stamp"; then
      log "$current is already back in place (a rollback stopped before it wrote the line); recording it"
      printf 'restored\t%s\n' "$root" >>"$record"
      continue
    fi
    if [ "$kind" = moved ] && [ ! -e "$current.bak-$stamp" ] && [ ! -L "$current.bak-$stamp" ]; then
      log "$current was never moved aside (the migrate stopped first); left as it is"
      continue
    fi
    if [ -e "$current" ] || [ -L "$current" ]; then
      mv "$current" "$current.native-$stamp" || fail "cannot move $current aside"
      log "moved $current to $current.native-$stamp"
    fi
    if [ "$kind" = moved ]; then
      mv "$current.bak-$stamp" "$current" || fail "cannot move $current.bak-$stamp back"
      log "moved $current.bak-$stamp back to $current"
    fi
    printf 'restored\t%s\n' "$root" >>"$record"
  done <<<"$lines"
}

restore_agmsg_links() {
  local home="$1"
  if [ -L "$home/.agents/skills/agmsg/db" ] || [ -L "$home/.agents/skills/agmsg/teams" ]; then
    agmsg_state "$home" restore
  fi
}

# The reason a lost path (relative to HOME) is no loss, or nothing. Every entry is a full path under one of MIGRATE_ROOTS,
# except the .apm-pin basename rule and the entries dropped from the catalog; docs/native-distribution.md lists them.
# Anything else counts as lost. $2 is the HOME the roots are read in, $3 the deployed record of migrate_roots.
allowed_lost_reason() {
  local path="$1" home="$2" deployed="$3" root rest name
  for root in $MIGRATE_ROOTS; do
    case "$path" in
      "$root/"*)
        rest="${path#"$root/"}"
        name="${rest%%/*}"
        if [ -f "$deployed" ] && [ ! -e "$home/$root/$name" ] && [ ! -L "$home/$root/$name" ] &&
          grep -qxF "$root"$'\t'"$name" "$deployed"; then
          echo "deployed by the previous native lock and not deployed this time"
          return
        fi
        ;;
    esac
  done
  case "$path" in
    .agents/skills/agmsg/run | .agents/skills/agmsg/run/*)
      echo "agmsg runtime state; the old path rebuilt the agmsg directory too, and apm replaces it"
      return
      ;;
    .claude/skills/synced | .claude/skills/synced/*)
      echo "Claude Code's synced-skill cache; the running session recreates it"
      return
      ;;
    .agents/skills/agmsg/apm.yml | .claude/skills/agmsg/apm.yml | \
      .agents/skills/agmsg/.apm | .claude/skills/agmsg/.apm | \
      .agents/skills/agmsg/.apm/.plugin-skill-sources.json | .claude/skills/agmsg/.apm/.plugin-skill-sources.json)
      echo "metadata the old path's stage wrote; the agmsg scripts do not read it"
      return
      ;;
  esac
  if [ "$(basename "$path")" = .apm-pin ]; then
    for root in $MIGRATE_ROOTS; do
      case "$path" in
        "$root/"*)
          echo "pin marker inside a root that migrate moved aside"
          return
          ;;
      esac
    done
  fi
}

# Tab-separated <path> <reason> for each lost path that is no loss. $2 and $3 are the arguments of allowed_lost_reason.
allowed_lost_paths() {
  local path reason
  while IFS= read -r path; do
    reason="$(allowed_lost_reason "$path" "$2" "$3")"
    if [ -n "$reason" ]; then printf '%s\t%s\n' "$path" "$reason"; fi
  done <"$1"
}

# apm 0.35.0 deletes deployed files it considers stale and `apm install --dry-run` does not preview that, so the same
# install and compile run on a clone of the backup first and the files that disappeared are counted.
cmd_rehearse() {
  parse_options "$@"
  [ -n "$SOURCE_REF" ] || fail "rehearse needs --source-ref"
  local home sha dir rehearsal scratch path manifest shared lost stamp escaping mode=plain
  local install_status=0 compile_status=skipped agmsg_status=0 linked=0 reinstate_status=skipped allowed_lost=0 baseline_skips=0 dropped=0
  home="$(target_home rehearse)"
  if ! native_lock_held "$home"; then native_lock_command "$home" rehearse "$@"; return; fi
  assert_default_apm_config "$home"
  assert_no_home_manifest "$home"
  assert_completed_backup "$home"
  escaping="$(root_escaping_links "$home")"
  [ -z "$escaping" ] || fail "these links in $MIGRATE_ROOTS of $home are broken or lead outside it, which migrate refuses and a rehearsal would hide by copying or dropping them. Replace each with a copy of its content (docs/native-distribution.md), run backup again, then re-run:
$escaping"
  assert_default_agmsg_store "$home"
  if [ "$MIGRATE" = 1 ]; then assert_same_render_mode "$home"; fi
  sha="$(resolve_source_sha "$SOURCE_REF")"
  dir="$(cd "$BACKUP_DIR" && pwd -P)"
  rehearsal="$(mktemp -d "$dir/rehearsal-$(date -u +%Y%m%dT%H%M%SZ).XXXXXX")"
  scratch="$rehearsal/home"
  mkdir "$scratch"
  : >"$rehearsal/apm.log"

  while IFS= read -r path; do
    [ -n "$path" ] || continue
    mkdir -p "$(dirname "$scratch/$path")"
    clone_copy "$dir/home/$path" "$scratch/$path"
  done <"$dir/present.txt"
  if [ -e "$home/.apm/apm_modules" ] || [ -L "$home/.apm/apm_modules" ]; then
    mkdir -p "$scratch/.apm"
    clone_copy "$home/.apm/apm_modules" "$scratch/.apm/apm_modules"
  fi
  if [ -d "$dir/agmsg-state" ]; then
    mkdir -p "$scratch/.local/state"
    clone_copy "$dir/agmsg-state" "$scratch/.local/state/agmsg"
  fi
  assert_default_apm_config "$scratch"
  assert_no_home_manifest "$scratch"
  isolate_scratch_links "$home" "$scratch"
  shared="$(shared_entries "$scratch")"
  [ -z "$shared" ] || fail "the scratch HOME $scratch still shares data with files outside it:
$shared"

  rehearsal_snapshot "$scratch" "$dir/present.txt" >"$rehearsal/before.txt"
  manifest="$(render_manifest "$sha" "$WORKSPACE_ONLY")"
  mkdir -p "$scratch/.apm"
  rm -f "$scratch/.apm/apm.yml"
  printf '%s\n' "$manifest" >"$scratch/.apm/apm.yml"

  if [ -L "$scratch/.agents/skills/agmsg/db" ]; then
    linked=1
    agmsg_state "$scratch" save
  fi
  if [ "$MIGRATE" = 1 ]; then
    mode=migrate
    stamp="$(date -u +%Y%m%dT%H%M%SZ)"
    claim_migrate_record "$scratch" "$stamp"
    migrate_roots "$scratch" "$stamp"
  fi
  run_apm_install "$scratch" 2>&1 | tee -a "$rehearsal/apm.log" >&2 || install_status=$?
  if [ "$install_status" -eq 0 ]; then
    compile_status=0
    run_apm "$scratch" compile -g --clean 2>&1 | tee -a "$rehearsal/apm.log" >&2 || compile_status=$?
  fi
  if [ "$MIGRATE" = 1 ] && [ "$install_status" = 0 ] && [ "$compile_status" = 0 ]; then
    reinstate_status=0
    (reinstate_entries "$scratch" "$stamp" "$rehearsal/") || reinstate_status=$?
  fi
  if [ "$linked" = 1 ]; then agmsg_state "$scratch" restore || agmsg_status=1; fi
  baseline_skips="$(grep -c 'no trustworthy local deployment baseline' "$rehearsal/apm.log" || true)"

  rehearsal_snapshot "$scratch" "$dir/present.txt" >"$rehearsal/after.txt"
  LC_ALL=C comm -23 "$rehearsal/before.txt" "$rehearsal/after.txt" >"$rehearsal/lost-all.txt"
  if [ "$MIGRATE" = 1 ]; then
    allowed_lost_paths "$rehearsal/lost-all.txt" "$scratch" "$(migrate_deployed_record "$scratch" "$stamp")" >"$rehearsal/allowed-lost.txt"
    LC_ALL=C comm -23 "$rehearsal/lost-all.txt" <(cut -f1 "$rehearsal/allowed-lost.txt") >"$rehearsal/lost.txt"
    allowed_lost="$(wc -l <"$rehearsal/allowed-lost.txt" | tr -d ' ')"
  else
    cp "$rehearsal/lost-all.txt" "$rehearsal/lost.txt"
  fi
  lost="$(wc -l <"$rehearsal/lost.txt" | tr -d ' ')"
  if [ "$MIGRATE" = 1 ]; then
    dropped_entries "$scratch" "$stamp" >"$rehearsal/dropped.txt"
    dropped="$(wc -l <"$rehearsal/dropped.txt" | tr -d ' ')"
  else
    : >"$rehearsal/dropped.txt"
  fi
  printf 'mode=%s\nhome=%s\nsource_ref=%s\nworkspace_only=%s\ninstall_status=%s\ncompile_status=%s\nreinstate_status=%s\nagmsg_status=%s\nlost=%s\nallowed_lost=%s\ndropped=%s\nbaseline_skips=%s\n%s\n' \
    "$mode" "$home" "$sha" "$WORKSPACE_ONLY" "$install_status" "$compile_status" "$reinstate_status" "$agmsg_status" "$lost" "$allowed_lost" "$dropped" "$baseline_skips" "$(cat "$dir/home-state.txt")" \
    >"$rehearsal/result.txt"

  if [ "$install_status" = 0 ] && [ "$compile_status" = 0 ] && [ "$agmsg_status" = 0 ] && [ "$lost" = 0 ] &&
    { [ "$MIGRATE" = 0 ] || { [ "$reinstate_status" = 0 ] && [ "$baseline_skips" = 0 ]; }; }; then
    log "rehearsal clean ($mode): install and compile ran on a clone of $dir and lost no file ($rehearsal)"
    return 0
  fi
  log "rehearsal failed ($mode): install=$install_status compile=$compile_status reinstate=$reinstate_status agmsg=$agmsg_status lost=$lost baseline_skips=$baseline_skips ($rehearsal/result.txt)"
  if [ "$lost" != 0 ]; then
    log "files that disappeared, all in $rehearsal/lost.txt:"
    head -n 20 "$rehearsal/lost.txt" | sed 's/^/  /' >&2
  fi
  exit 1
}

home_flags() {
  if [ "$REAL_HOME" = 1 ]; then printf '%s' "--real-home"; else printf '%s' "--home $1"; fi
}

cmd_reinstate() {
  parse_options "$@"
  [ -n "$STAMP" ] || fail "reinstate needs --stamp <UTC stamp of the migrate>"
  assert_stamp "$STAMP"
  local home
  home="$(target_home reinstate)"
  if ! native_lock_held "$home"; then native_lock_command "$home" reinstate "$@"; return; fi
  reinstate_entries "$home" "$STAMP" "$home/.apm/native-reinstate-$STAMP."
}

assert_not_checkout() {
  local home="$1" repo
  if [ -e "$home/.apm/.git" ] || [ -L "$home/.apm/.git" ] || [ -e "$home/.apm/catalog" ] || [ -L "$home/.apm/catalog" ]; then
    fail "$home/.apm is an authoring checkout (.git or catalog/), and apm writes its manifest and lock there. Move the checkout out of $home/.apm first (docs/native-distribution.md)."
  fi
  repo="$(physical_path "$REPO_ROOT")"
  case "$repo/" in
    "$(physical_path "$home/.apm")/"*) fail "this repository ($repo) is inside $home/.apm, the directory migrate writes" ;;
  esac
}

result_has() {
  grep -qxF "$2" "$1/result.txt"
}

# "<root>/<entry>" for each entry the previous native lock deployed that the roots of $1 lack now.
dropped_entries() {
  local home="$1" stamp="$2" deployed root name
  deployed="$(migrate_deployed_record "$home" "$stamp")"
  [ -f "$deployed" ] || return 0
  while IFS=$'\t' read -r root name; do
    [ -n "$root" ] || continue
    if [ ! -e "$home/$root/$name" ] && [ ! -L "$home/$root/$name" ]; then printf '%s/%s\n' "$root" "$name"; fi
  done <"$deployed"
}

# The two facts of the real HOME that decide what a rehearsal means: whether a previous native lock exists, and what
# ~/.apm is. A rehearsal taken in another state is not accepted by migrate.
home_state_lines() {
  local home="$1" apm_state=absent
  if [ -e "$home/.apm/.git" ] || [ -d "$home/.apm/catalog" ]; then
    apm_state=checkout
  elif [ -e "$home/.apm" ] || [ -L "$home/.apm" ]; then
    apm_state=consumer
  fi
  if [ -f "$home/.apm/apm.lock.yaml" ]; then printf 'previous_lock=present\n'; else printf 'previous_lock=absent\n'; fi
  printf 'home_apm=%s\n' "$apm_state"
}

assert_migrate_rehearsal() {
  local home="$1" sha="$2" dir="$3" want
  [ -f "$dir/result.txt" ] || fail "--rehearsal $dir has no result.txt; run rehearse --migrate and pass its rehearsal-<UTC> directory"
  for want in mode=migrate "home=$home" "source_ref=$sha" "workspace_only=$WORKSPACE_ONLY" install_status=0 compile_status=0 \
    reinstate_status=0 agmsg_status=0 lost=0 baseline_skips=0; do
    result_has "$dir" "$want" || fail "the rehearsal $dir does not show $want; run rehearse --migrate again for this HOME, --source-ref and --workspace-only until it is clean"
  done
  for want in $(home_state_lines "$home"); do
    result_has "$dir" "$want" || fail "the rehearsal $dir was taken when the HOME was in another state (it does not show $want); take a backup and run rehearse --migrate again now"
  done
  [ -f "$dir/dropped.txt" ] || fail "the rehearsal $dir has no dropped.txt; run rehearse --migrate again"
  [ -f "$dir/skipped.txt" ] && [ ! -L "$dir/skipped.txt" ] || fail "the rehearsal $dir has no plain skipped.txt; run rehearse --migrate again"
}

# The entries migrate drops must be the ones the rehearsal dropped, because the rehearsal is what allowed them. The rollback
# that follows a mismatch keeps every file.
assert_dropped_as_rehearsed() {
  local home="$1" stamp="$2" dir="$3" actual
  actual="$home/.apm/native-migrate-$stamp.dropped.txt"
  dropped_entries "$home" "$stamp" >"$actual"
  [ "$(sort "$actual")" = "$(sort "$dir/dropped.txt")" ] ||
    fail "migrate dropped other entries than the rehearsal did (compare $actual with $dir/dropped.txt); the roots are rolled back"
}

assert_skipped_as_rehearsed() {
  local home="$1" stamp="$2" dir="$3" actual
  actual="$home/.apm/native-migrate-$stamp.skipped.txt"
  [ -f "$actual" ] && [ ! -L "$actual" ] || fail "migrate has no plain skipped.txt; the roots are rolled back"
  [ "$(LC_ALL=C sort "$actual")" = "$(LC_ALL=C sort "$dir/skipped.txt")" ] ||
    fail "migrate replaced different entries than the rehearsal did (compare $actual with $dir/skipped.txt); the roots are rolled back"
}

# Copies the files migrate must not change (owner-only, permissions kept) so a change can be undone. Contents are never
# logged. saved.txt lists, one file at a time and only once it is settled, whether the file was there (present, copy
# finished) or not (absent); a restore touches only the files listed, so a failure part way leaves the others alone.
save_untouched() {
  local home="$1" stamp="$2" dir path
  dir="$home/.apm/native-migrate-$stamp.untouched"
  (umask 077 && mkdir -p "$dir") || fail "cannot create $dir"
  : >"$dir/saved.txt"
  for path in $MIGRATE_UNTOUCHED_FILES; do
    if [ -f "$home/$path" ]; then
      (umask 077 && mkdir -p "$(dirname "$dir/$path")") || fail "cannot create $dir/$(dirname "$path")"
      cp -p "$home/$path" "$dir/$path" || fail "cannot copy $home/$path"
      printf 'present\t%s\n' "$path" >>"$dir/saved.txt"
    else
      printf 'absent\t%s\n' "$path" >>"$dir/saved.txt"
    fi
  done
}

changed_untouched_files() {
  local home="$1" stamp="$2" dir kind path
  dir="$home/.apm/native-migrate-$stamp.untouched"
  [ -f "$dir/saved.txt" ] || return 0
  while IFS=$'\t' read -r kind path; do
    [ -n "$path" ] || continue
    if [ "$kind" = present ]; then
      if [ ! -f "$home/$path" ] || [ "$(sha256 <"$home/$path")" != "$(sha256 <"$dir/$path")" ]; then printf '%s\n' "$path"; fi
    elif [ -e "$home/$path" ] || [ -L "$home/$path" ]; then
      printf '%s\n' "$path"
    fi
  done <"$dir/saved.txt"
}

# Puts the saved copy back; the version migrate left stays beside it as <path>.changed-<stamp>. A file that is a working
# link is written through, so the link stays and its target gets the old content.
restore_untouched() {
  local home="$1" stamp="$2" dir path
  dir="$home/.apm/native-migrate-$stamp.untouched"
  [ -f "$dir/saved.txt" ] || return 0
  for path in $(changed_untouched_files "$home" "$stamp"); do
    if [ -L "$home/$path" ] && [ -e "$home/$path" ] && [ -f "$dir/$path" ]; then
      cp -p "$home/$path" "$home/$path.changed-$stamp" || fail "cannot keep $home/$path as $path.changed-$stamp"
      cat "$dir/$path" >"$home/$path" || fail "cannot restore $home/$path"
    else
      if [ -e "$home/$path" ] || [ -L "$home/$path" ]; then
        mv "$home/$path" "$home/$path.changed-$stamp" || fail "cannot move $home/$path aside"
      fi
      if [ -f "$dir/$path" ]; then cp -p "$dir/$path" "$home/$path" || fail "cannot restore $home/$path"; fi
    fi
    log "restored $home/$path; the version migrate left is $home/$path.changed-$stamp"
  done
}

# Fails, and lists them in <HOME>/.apm/native-migrate-<stamp>.lost.txt, when a path of the roots that existed before migrate
# is gone and is not in the allowlist of rehearse. The same check as the rehearsal, made on the HOME migrate wrote.
assert_no_unexpected_loss() {
  local home="$1" stamp="$2" before="$3" dir lost_file
  lost_file="$home/.apm/native-migrate-$stamp.lost.txt"
  dir="$(mktemp -d "$home/.apm/.native-migrate.XXXXXX")" || fail "cannot create a temporary directory in $home/.apm"
  grep -v '^$' <<<"$before" >"$dir/before" || true
  migrate_roots_snapshot "$home" >"$dir/after"
  LC_ALL=C comm -23 "$dir/before" "$dir/after" >"$dir/lost-all"
  allowed_lost_paths "$dir/lost-all" "$home" "$(migrate_deployed_record "$home" "$stamp")" | cut -f1 >"$dir/allowed"
  LC_ALL=C comm -23 "$dir/lost-all" "$dir/allowed" >"$lost_file"
  rm -rf "$dir"
  [ ! -s "$lost_file" ] || fail "these files of the roots existed before migrate and are gone, and are not in the allowlist (listed in $lost_file; they are kept in <root>.bak-$stamp):
$(head -n 20 "$lost_file" | sed 's/^/  /')"
}

migrate_roots_snapshot() {
  rehearsal_snapshot "$1" <(tr ' ' '\n' <<<"$MIGRATE_ROOTS")
}

manifest_is_rendered() {
  case "$(head -n 1 "$1/.apm/apm.yml" 2>/dev/null || true)" in
    "# Rendered by scripts/native.sh"*) return 0 ;;
    *) return 1 ;;
  esac
}

# Runs from the EXIT trap of cmd_migrate once the roots may have moved: undo the move, keep every file, keep the exit status.
# Each step runs in its own subshell so that a fail in one cannot skip the next.
migrate_failure() {
  local status=$?
  trap - EXIT
  log "migrate failed (exit $status)"
  if [ -f "$(migrate_record "$MIGRATE_HOME" "$MIGRATE_STAMP")" ]; then
    log "rolling the roots back"
    (rollback_roots "$MIGRATE_HOME" "$MIGRATE_STAMP") || log "the automatic rollback failed; fix the cause, then run migrate-rollback --stamp $MIGRATE_STAMP"
    if [ "$MIGRATE_AGMSG_LINKED" = 1 ]; then
      (agmsg_state "$MIGRATE_HOME" restore) || log "the agmsg links were not restored; run mise run agmsg:state:restore"
    fi
  fi
  if (restore_untouched "$MIGRATE_HOME" "$MIGRATE_STAMP"); then
    rm -rf "${MIGRATE_HOME:?}/.apm/native-migrate-$MIGRATE_STAMP.untouched"
  else
    log "the files $MIGRATE_UNTOUCHED_FILES were not restored; the copies are in $MIGRATE_HOME/.apm/native-migrate-$MIGRATE_STAMP.untouched"
  fi
  if manifest_is_rendered "$MIGRATE_HOME"; then
    log "only the roots were rolled back: $MIGRATE_HOME/.apm/apm.yml is still the rendered manifest, so ~/.apm stays the native consumer. To go back to the checkout state, move the consumer ~/.apm aside and put ~/.apm.checkout-<UTC> back; the old tools are at commit 0bcce09 (docs/native-distribution.md, the section on moving the checkout)"
  fi
  exit "$status"
}

cmd_migrate() {
  parse_options "$@"
  [ -n "$SOURCE_REF" ] || fail "migrate needs --source-ref; deploying never moves a pin on its own"
  [ -n "$REHEARSAL" ] || fail "migrate needs --rehearsal <the rehearsal-<UTC> directory of a clean rehearse --migrate>"
  local home sha edited links manifest roots_before changed rehearsal_dir
  home="$(target_home migrate)"
  sha="$(resolve_source_sha "$SOURCE_REF")"
  assert_not_checkout "$home"
  if ! native_lock_held "$home"; then native_lock_command "$home" migrate "$@"; return; fi
  assert_same_render_mode "$home"
  rehearsal_dir="$(cd "$REHEARSAL" 2>/dev/null && pwd -P || printf '%s' "$REHEARSAL")"
  assert_migrate_rehearsal "$home" "$sha" "$rehearsal_dir"

  assert_default_apm_config "$home"
  assert_no_home_manifest "$home"
  edited="$(edited_generated_roots "$home")"
  [ -z "$edited" ] || fail "these roots keep APM's marker but were edited after compile, and apm compile would overwrite them:
$edited
Delete the marker line to keep the file as hand-written, or move it aside, then re-run."
  if [ "$REAL_HOME" = 1 ]; then links="$(real_home_shared_entries "$home")"; else links="$(shared_entries "$home")"; fi
  [ -z "$links" ] || fail "these entries of $home may share their data with files outside it, so writing them would change those files:
$links
Move them aside or make them plain directories and files of this HOME."

  assert_default_agmsg_store "$home"
  manifest="$(render_manifest "$sha" "$WORKSPACE_ONLY")"
  roots_before="$(migrate_roots_snapshot "$home")"
  MIGRATE_HOME="$home" MIGRATE_STAMP="$(date -u +%Y%m%dT%H%M%SZ)"
  claim_migrate_record "$home" "$MIGRATE_STAMP"
  log "native-migrate stamp: $MIGRATE_STAMP"
  MIGRATE_AGMSG_LINKED=0
  if [ -L "$home/.agents/skills/agmsg/db" ]; then
    MIGRATE_AGMSG_LINKED=1
    agmsg_state "$home" save
  fi

  trap migrate_failure EXIT
  save_untouched "$home" "$MIGRATE_STAMP"
  install_manifest "$home" "$manifest"
  migrate_roots "$home" "$MIGRATE_STAMP"
  run_apm_install "$home"
  run_apm "$home" compile -g --clean
  reinstate_entries "$home" "$MIGRATE_STAMP" "$home/.apm/native-migrate-$MIGRATE_STAMP."
  if [ "$MIGRATE_AGMSG_LINKED" = 1 ]; then agmsg_state "$home" restore; fi
  assert_dropped_as_rehearsed "$home" "$MIGRATE_STAMP" "$rehearsal_dir"
  assert_skipped_as_rehearsed "$home" "$MIGRATE_STAMP" "$rehearsal_dir"
  assert_no_unexpected_loss "$home" "$MIGRATE_STAMP" "$roots_before"
  changed="$(changed_untouched_files "$home" "$MIGRATE_STAMP")"
  [ -z "$changed" ] || fail "migrate changed these files, which it must leave alone (they are put back, and the changed versions kept as <file>.changed-$MIGRATE_STAMP): $(tr '\n' ' ' <<<"$changed")"
  rm -rf "${home:?}/.apm/native-migrate-$MIGRATE_STAMP.untouched"
  trap - EXIT

  log "migrated $home; the previous roots are kept as <root>.bak-$MIGRATE_STAMP (record: $(migrate_record "$home" "$MIGRATE_STAMP"))"
  log "to undo: mise run native:migrate-rollback -- $(home_flags "$home") --stamp $MIGRATE_STAMP"
  printf '%s\n' "$MIGRATE_STAMP"
}

cmd_migrate_rollback() {
  parse_options "$@"
  [ -n "$STAMP" ] || fail "migrate-rollback needs --stamp <UTC stamp of the migrate>"
  assert_stamp "$STAMP"
  local home
  home="$(target_home migrate-rollback)"
  if ! native_lock_held "$home"; then native_lock_command "$home" migrate-rollback "$@"; return; fi
  rollback_roots "$home" "$STAMP"
  restore_agmsg_links "$home"
  log "rolled $home back to the roots of $STAMP; the roots native wrote are kept as <root>.native-$STAMP"
}

main() {
  local command="${1:-}"
  if [ $# -gt 0 ]; then shift; fi
  case "$command" in
    sync)
      # shellcheck source=scripts/native-sync.sh
      . "$SCRIPT_DIR/native-sync.sh"
      cmd_sync "$@"
      ;;
    plan) cmd_plan "$@" ;;
    render) cmd_render "$@" ;;
    apply) cmd_apply "$@" ;;
    backup) cmd_backup "$@" ;;
    rehearse) cmd_rehearse "$@" ;;
    migrate) cmd_migrate "$@" ;;
    migrate-rollback) cmd_migrate_rollback "$@" ;;
    reinstate) cmd_reinstate "$@" ;;
    opencode) cmd_opencode "$@" ;;
    *) printf 'error: unknown native command: %s\n' "$command" >&2; exit 2 ;;
  esac
}

if [[ "${BASH_SOURCE[0]}" = "$0" ]]; then main "$@"; fi
