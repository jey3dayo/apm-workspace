#!/usr/bin/env bash
# Native APM distribution: a consumer manifest pins this repository's packages by commit SHA, and `apm install -g`
# followed by `apm compile -g --clean` deploy them. What APM does not deploy is listed in docs/native-distribution.md
# and stays manual; this script adds no sync of its own.
#
# apply targets a disposable HOME and refuses the account's real HOME, its ancestors and the tool state inside it.
# Applying to the real HOME is blocked (docs/native-distribution.md); backup and rehearse can read it.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
ROOT_MANIFEST="$REPO_ROOT/apm.yml"
SOURCE_URL="${APM_NATIVE_SOURCE_URL:-https://github.com/jey3dayo/apm-workspace.git}"
APM_BIN="${APM_BIN:-apm}"
GENERATED_ROOT_MARKER="<!-- Generated by APM CLI from .apm/ primitives -->"
# Roots `apm compile -g` may write. An edited copy that kept APM's marker would be overwritten without notice.
COMPILED_ROOTS=".claude/CLAUDE.md .codex/AGENTS.md .cursor/AGENTS.md"
PROTECTED_SURFACES=".apm .claude .codex .cursor .agents .config .cache .local Library"
# Non-secret paths apply can change; backup copies them and rehearse reproduces them in a scratch HOME. Tool configs that
# may hold credentials (~/.codex/config.toml, MCP configs) are not here, which is why apply installs with --only apm.
BACKUP_PATHS=".apm/apm.yml .apm/config.json .apm/apm.lock.yaml .apm/deployment-receipts .claude/skills .claude/agents .claude/rules .claude/commands .claude/CLAUDE.md
.codex/AGENTS.md .codex/rules .cursor/agents .cursor/rules .cursor/AGENTS.md .agents/skills AGENTS.md .config/opencode/AGENTS.md"

usage() {
  cat <<'EOF'
Usage: scripts/native.sh <command> [options]

  plan     [--source-ref REF] [--workspace-only]  Print the consumer manifest and the steps apply would run. Writes nothing.
  render   --source-ref REF [--workspace-only]    Print the consumer manifest to stdout.
  backup   (--home DIR | --real-home) --backup-dir NEW_DIR
                                                 Copy the non-secret paths apply can change, plus the agmsg store.
  rehearse (--home DIR | --real-home) --backup-dir DIR --source-ref REF [--workspace-only]
                                                 Clone a completed backup into a scratch HOME inside DIR, run the same
                                                 install and compile there, and count the files that disappeared.
  apply    --home DIR --source-ref REF [--workspace-only]
                                                 Write the manifest into <HOME>/.apm, then apm install -g --only apm and
                                                 apm compile -g --clean with that HOME, which must be disposable.
                                                 --real-home is blocked (docs/native-distribution.md).

REF is a commit of this repository (or a full 40-hex SHA). --workspace-only keeps only the catalog and manual-skills
packages and drops external dependencies and MCP servers.
EOF
}

fail() {
  printf 'error: %s\n' "$*" >&2
  exit 1
}

log() {
  printf '%s\n' "$*" >&2
}

resolve_source_sha() {
  local ref="$1" sha
  if sha=$(git -C "$REPO_ROOT" rev-parse --verify --quiet "$ref^{commit}" 2>/dev/null); then
    printf '%s\n' "$sha"
  elif [[ "$ref" =~ ^[0-9a-f]{40}$ ]]; then
    printf '%s\n' "$ref"
  else
    fail "--source-ref $ref is neither a commit of $REPO_ROOT nor a full 40-hex SHA"
  fi
}

# Rewrites the two floating workspace refs (catalog#main, manual-skills#main) into SHA pins. External dependencies are
# already pinned in apm.yml and pass through unchanged.
render_manifest() {
  local sha="$1" workspace_only="$2"
  [ -f "$ROOT_MANIFEST" ] || fail "missing $ROOT_MANIFEST"
  printf '# Rendered by scripts/native.sh from apm.yml with this repository pinned at %s. Do not edit; re-render.\n' "$sha"
  awk -v sha="$sha" -v url="$SOURCE_URL" -v only="$workspace_only" '
    /^[^ #]/ { section = $0; sub(/:.*/, "", section); group = "" }
    section == "dependencies" && /^  [a-z]+:/ { group = $1 }
    /^    - jey3dayo\/apm-workspace\/(catalog|manual-skills)#main[ ]*$/ {
      pkg = $0
      sub(/^.*apm-workspace\//, "", pkg)
      sub(/#main.*$/, "", pkg)
      printf "    - git: %s\n      path: %s\n      ref: %s\n", url, pkg, sha
      pinned[pkg]++
      next
    }
    only && section == "dependencies" && group == "mcp:" { next }
    only && section == "dependencies" && group == "apm:" && !/^  apm:/ { next }
    { print }
    END { exit !(pinned["catalog"] == 1 && pinned["manual-skills"] == 1) }
  ' "$ROOT_MANIFEST" || fail "apm.yml must list jey3dayo/apm-workspace/catalog#main and manual-skills#main exactly once each"
}

physical_path() {
  local path="$1" rest=""
  while [ ! -d "$path" ]; do
    rest="/$(basename "$path")$rest"
    path="$(dirname "$path")"
  done
  printf '%s%s\n' "$(cd "$path" && pwd -P)" "$rest"
}

# The account's home from the user database, not $HOME, so a HOME override cannot hide the real one.
# APM_NATIVE_ACCOUNT_HOME stands in for it in tests, which never touch the real one.
account_home() {
  local user home
  if [ -n "${APM_NATIVE_ACCOUNT_HOME:-}" ]; then
    [ -d "$APM_NATIVE_ACCOUNT_HOME" ] || fail "APM_NATIVE_ACCOUNT_HOME=$APM_NATIVE_ACCOUNT_HOME is not a directory"
    physical_path "$APM_NATIVE_ACCOUNT_HOME"
    return
  fi
  user="$(id -un)"
  home="$(eval "printf '%s' ~$user")"
  physical_path "$home"
}

assert_disposable_home() {
  local dir="$1" home surface prefix
  case "/$dir/" in
    */../*) fail "--home $dir must not contain '..'" ;;
  esac
  [ -d "$dir" ] || fail "--home $dir is not an existing directory"
  dir="$(cd "$dir" && pwd -P)"
  home="$(account_home)"
  case "$home/" in
    "${dir%/}/"*) fail "--home $dir is the account's HOME or contains it; the cutover is not part of this script (docs/native-distribution.md)" ;;
  esac
  for surface in $PROTECTED_SURFACES; do
    for prefix in "$home/$surface/" "$(physical_path "$home/$surface")/"; do
      case "$dir/" in
        "$prefix"*) fail "--home $dir is inside $home/$surface" ;;
      esac
    done
  done
  printf '%s\n' "$dir"
}

# APM reads a root with Python's splitlines(): CRLF and a lone CR both end a line.
root_lines() {
  awk '{ sub(/\r$/, ""); gsub(/\r/, "\n"); print }' "$1"
}

has_marker() {
  local first
  first="$(root_lines "$1" | LC_ALL=C sed -n '/[^[:space:]]/{p;q;}')"
  [ "${first#"$GENERATED_ROOT_MARKER"}" != "$first" ]
}

# apm_cli/compilation/build_id.py: the 12-hex Build ID is the sha256 of the file without that line, lines joined by
# "\n". Any edit after compile breaks the match.
has_valid_build_id() {
  local pattern='^<!-- Build ID: [0-9a-f]{12} -->$' recorded computed
  recorded="$(root_lines "$1" | grep -E "$pattern" | sed -E 's/^<!-- Build ID: ([0-9a-f]{12}) -->$/\1/')"
  [ "$(printf '%s\n' "$recorded" | grep -c .)" = 1 ] || return 1
  computed="$(root_lines "$1" | grep -vE "$pattern" | awk '{ if (n++) printf "\n"; printf "%s", $0 }' | sha256 | cut -c1-12)"
  [ "$recorded" = "$computed" ]
}

sha256() {
  if command -v sha256sum >/dev/null 2>&1; then sha256sum | awk '{print $1}'; else shasum -a 256 | awk '{print $1}'; fi
}

edited_generated_roots() {
  local home="$1" root
  for root in $COMPILED_ROOTS; do
    if [ -f "$home/$root" ] && has_marker "$home/$root" && ! has_valid_build_id "$home/$root"; then
      printf '%s\n' "$home/$root"
    fi
  done
}

parse_options() {
  HOME_DIR="" SOURCE_REF="" WORKSPACE_ONLY=0 REAL_HOME=0 BACKUP_DIR=""
  while [ $# -gt 0 ]; do
    case "$1" in
      --home) [ $# -ge 2 ] || fail "--home needs a value"; HOME_DIR="$2"; shift 2 ;;
      --real-home) REAL_HOME=1; shift ;;
      --backup-dir) [ $# -ge 2 ] || fail "--backup-dir needs a value"; BACKUP_DIR="$2"; shift 2 ;;
      --source-ref) [ $# -ge 2 ] || fail "--source-ref needs a value"; SOURCE_REF="$2"; shift 2 ;;
      --workspace-only) WORKSPACE_ONLY=1; shift ;;
      *) fail "unknown option: $1" ;;
    esac
  done
}

cmd_render() {
  parse_options "$@"
  [ -n "$SOURCE_REF" ] || fail "render needs --source-ref"
  render_manifest "$(resolve_source_sha "$SOURCE_REF")" "$WORKSPACE_ONLY"
}

cmd_plan() {
  parse_options "$@"
  local sha
  sha="$(resolve_source_sha "${SOURCE_REF:-HEAD}")"
  printf '# Source: %s at %s\n' "$SOURCE_URL" "$sha"
  if [ -z "$(git -C "$REPO_ROOT" branch -r --contains "$sha" 2>/dev/null)" ]; then
    printf '# Warning: no remote branch contains %s yet; apm cannot fetch it until it is pushed.\n' "$sha"
  fi
  printf '# Consumer manifest (written to <HOME>/.apm/apm.yml by apply):\n\n'
  render_manifest "$sha" "$WORKSPACE_ONLY"
  cat <<EOF

# apply --home <disposable HOME> --source-ref $sha would run:
#   1. stop if an APM-generated root there was edited after compile ($COMPILED_ROOTS), or if a symlink or hard link
#      inside that HOME reaches outside it
#   2. stop if <HOME>/.apm/config.json holds more than default_client and prefer_ssh; keep a differing
#      <HOME>/.apm/apm.yml as apm.yml.<UTC>.bak
#   3. write the manifest above
#   4. apm install -g --only apm, from an empty environment plus HOME, PATH, locale, git config locations and a
#      TMPDIR in HOME; MCP servers stay as they are
#   5. apm compile -g --clean, the same way
# apply --real-home is blocked (docs/native-distribution.md).
# Not deployed by APM, and left to the manual steps in docs/native-distribution.md: agmsg db/teams links,
# catalog/rules and catalog/claude/rules, private skills, OpenCode and Pi instructions, host-local MCP.
# This plan wrote nothing.
EOF
}

# backup and rehearse: --home names a disposable HOME, --real-home the account's own. Exactly one of them.
target_home() {
  if [ "$REAL_HOME" = 1 ]; then
    [ -z "$HOME_DIR" ] || fail "pass either --home or --real-home, not both"
    account_home
  else
    [ -n "$HOME_DIR" ] || fail "$1 needs --home <disposable HOME>, or --real-home for the account's HOME"
    assert_disposable_home "$HOME_DIR"
  fi
}

cmd_apply() {
  parse_options "$@"
  [ "$REAL_HOME" = 0 ] || fail "applying to the real HOME is blocked: apm install deletes skills the old writer deployed and migrates Codex plugins (docs/native-distribution.md, 「実 HOME への切り替えの blocker」). Use native:rehearse to try a backup instead."
  [ -n "$SOURCE_REF" ] || fail "apply needs --source-ref; deploying never moves a pin on its own"
  [ -n "$HOME_DIR" ] || fail "apply needs --home <disposable HOME>"
  local home sha manifest edited links tmp
  home="$(assert_disposable_home "$HOME_DIR")"
  sha="$(resolve_source_sha "$SOURCE_REF")"
  assert_default_apm_config "$home"
  edited="$(edited_generated_roots "$home")"
  [ -z "$edited" ] || fail "these roots keep APM's marker but were edited after compile, and apm compile would overwrite them:
$edited
Delete the marker line to keep the file as hand-written, or move it aside, then re-run."

  links="$(shared_entries "$home")"
  [ -z "$links" ] || fail "these entries inside $home may share their data with files outside it, so writing them would change those files:
$links
Move them aside or make them plain directories and files of this HOME."

  manifest="$(render_manifest "$sha" "$WORKSPACE_ONLY")"
  mkdir -p "$home/.apm"
  # A new file renamed into place, so a hard link at apm.yml keeps the other file's contents.
  tmp="$(mktemp "$home/.apm/.apm.yml.XXXXXX")"
  printf '%s\n' "$manifest" >"$tmp"
  if [ -f "$home/.apm/apm.yml" ] && ! cmp -s "$tmp" "$home/.apm/apm.yml"; then
    keep_previous_manifest "$home"
  fi
  mv -f "$tmp" "$home/.apm/apm.yml"

  run_apm "$home" install -g --only apm
  run_apm "$home" compile -g --clean
}

keep_previous_manifest() {
  local home="$1" stamp bak n=1
  stamp="$(date -u +%Y%m%dT%H%M%SZ)"
  bak="$home/.apm/apm.yml.$stamp.bak"
  while [ -e "$bak" ] || [ -L "$bak" ]; do
    bak="$home/.apm/apm.yml.$stamp.$n.bak"
    n=$((n + 1))
  done
  cp -p "$home/.apm/apm.yml" "$bak"
  log "kept the previous manifest as $bak"
}

assert_backup_dir_outside_targets() {
  local home="$1" dir="$2" surface
  for surface in .apm .claude .codex .cursor .agents; do
    case "$dir/" in
      "$home/$surface/"*) fail "--backup-dir $dir must not be inside $home/$surface" ;;
    esac
  done
}

cmd_backup() {
  parse_options "$@"
  [ -n "$BACKUP_DIR" ] || fail "backup needs --backup-dir <new directory>"
  local home dir path
  home="$(target_home backup)"
  dir="$(physical_path "$BACKUP_DIR")"
  assert_backup_dir_outside_targets "$home" "$dir"
  if [ -e "$dir" ] && [ -n "$(ls -A "$dir")" ]; then fail "--backup-dir $dir already has files; backups are never overwritten"; fi
  mkdir -p "$dir/home"
  : >"$dir/present.txt"
  : >"$dir/absent.txt"
  for path in $BACKUP_PATHS; do
    if [ -e "$home/$path" ] || [ -L "$home/$path" ]; then
      mkdir -p "$(dirname "$dir/home/$path")"
      clone_copy "$home/$path" "$dir/home/$path"
      printf '%s\n' "$path" >>"$dir/present.txt"
    else
      printf '%s\n' "$path" >>"$dir/absent.txt"
    fi
  done
  if [ -d "$home/.local/state/agmsg" ]; then clone_copy "$home/.local/state/agmsg" "$dir/agmsg-state"; fi
  printf 'home=%s\ncreated=%s\n' "$home" "$(date -u +%Y-%m-%dT%H:%M:%SZ)" >"$dir/complete"
  log "backed up $(wc -l <"$dir/present.txt" | tr -d ' ') paths of $home into $dir"
}

# APFS clones on macOS; a plain copy elsewhere. Symlinks stay symlinks.
clone_copy() {
  cp -cpR "$1" "$2" 2>/dev/null || cp -pR "$1" "$2"
}

assert_completed_backup() {
  local home="$1"
  [ -n "$BACKUP_DIR" ] || fail "rehearse needs --backup-dir <a completed backup of this HOME>; run backup first"
  [ -f "$BACKUP_DIR/complete" ] || fail "$BACKUP_DIR is not a completed backup"
  grep -qxF "home=$home" "$BACKUP_DIR/complete" || fail "$BACKUP_DIR is a backup of another HOME"
}

# Every symlink of the scratch HOME ends up inside it, so nothing apm writes there reaches the real files.
isolate_scratch_links() {
  local home="$1" scratch="$2" link target resolved
  local store="$home/.local/state/agmsg/"
  while IFS= read -r link; do
    target="$(readlink "$link")"
    case "$target" in
      "$store"*)
        rm -f "$link"
        ln -s "$scratch/.local/state/agmsg/${target#"$store"}" "$link"
        ;;
      *)
        if [ ! -e "$link" ] || ! resolved="$(realpath "$link" 2>/dev/null)"; then
          rm -f "$link"
          log "removed the broken link $link -> $target from the scratch HOME"
          continue
        fi
        case "$resolved/" in
          "$scratch/"*) ;;
          *)
            rm -f "$link"
            cp -cpRL "$resolved" "$link" 2>/dev/null || {
              rm -rf "$link"
              cp -pRL "$resolved" "$link"
            }
            ;;
        esac
        ;;
    esac
  done < <(find "$scratch" -type l | LC_ALL=C sort)
}

rehearsal_snapshot() {
  local scratch="$1" present="$2" path
  (cd "$scratch" && while IFS= read -r path; do
    [ -n "$path" ] || continue
    if [ -e "$path" ] || [ -L "$path" ]; then find "$path"; fi
  done <"$present" | LC_ALL=C sort)
}

agmsg_state() {
  env -u XDG_STATE_HOME HOME="$1" bash "$REPO_ROOT/scripts/agmsg-state.sh" "$2" >&2
}

# apm 0.35.0 deletes deployed files it considers stale and `apm install --dry-run` does not preview that, so the same
# install and compile run on a clone of the backup first and the files that disappeared are counted.
cmd_rehearse() {
  parse_options "$@"
  [ -n "$SOURCE_REF" ] || fail "rehearse needs --source-ref"
  local home sha dir rehearsal scratch path manifest shared lost
  local install_status=0 compile_status=skipped agmsg_status=0 linked=0
  home="$(target_home rehearse)"
  assert_default_apm_config "$home"
  assert_completed_backup "$home"
  sha="$(resolve_source_sha "$SOURCE_REF")"
  dir="$(cd "$BACKUP_DIR" && pwd -P)"
  rehearsal="$(mktemp -d "$dir/rehearsal-$(date -u +%Y%m%dT%H%M%SZ).XXXXXX")"
  scratch="$rehearsal/home"
  mkdir "$scratch"

  while IFS= read -r path; do
    [ -n "$path" ] || continue
    mkdir -p "$(dirname "$scratch/$path")"
    clone_copy "$dir/home/$path" "$scratch/$path"
  done <"$dir/present.txt"
  if [ -e "$home/.apm/apm_modules" ] || [ -L "$home/.apm/apm_modules" ]; then
    mkdir -p "$scratch/.apm"
    clone_copy "$home/.apm/apm_modules" "$scratch/.apm/apm_modules"
  fi
  if [ -d "$dir/agmsg-state" ]; then
    mkdir -p "$scratch/.local/state"
    clone_copy "$dir/agmsg-state" "$scratch/.local/state/agmsg"
  fi
  assert_default_apm_config "$scratch"
  isolate_scratch_links "$home" "$scratch"
  shared="$(shared_entries "$scratch")"
  [ -z "$shared" ] || fail "the scratch HOME $scratch still shares data with files outside it:
$shared"

  rehearsal_snapshot "$scratch" "$dir/present.txt" >"$rehearsal/before.txt"
  manifest="$(render_manifest "$sha" "$WORKSPACE_ONLY")"
  mkdir -p "$scratch/.apm"
  rm -f "$scratch/.apm/apm.yml"
  printf '%s\n' "$manifest" >"$scratch/.apm/apm.yml"

  if [ -L "$scratch/.agents/skills/agmsg/db" ]; then
    linked=1
    agmsg_state "$scratch" save
  fi
  run_apm "$scratch" install -g --only apm 2>&1 | tee -a "$rehearsal/apm.log" >&2 || install_status=$?
  if [ "$install_status" -eq 0 ]; then
    compile_status=0
    run_apm "$scratch" compile -g --clean 2>&1 | tee -a "$rehearsal/apm.log" >&2 || compile_status=$?
  fi
  if [ "$linked" = 1 ]; then agmsg_state "$scratch" restore || agmsg_status=1; fi

  rehearsal_snapshot "$scratch" "$dir/present.txt" >"$rehearsal/after.txt"
  LC_ALL=C comm -23 "$rehearsal/before.txt" "$rehearsal/after.txt" >"$rehearsal/lost.txt"
  lost="$(wc -l <"$rehearsal/lost.txt" | tr -d ' ')"
  printf 'home=%s\nsource_ref=%s\ninstall_status=%s\ncompile_status=%s\nagmsg_status=%s\nlost=%s\n' \
    "$home" "$sha" "$install_status" "$compile_status" "$agmsg_status" "$lost" >"$rehearsal/result.txt"

  if [ "$install_status" = 0 ] && [ "$compile_status" = 0 ] && [ "$agmsg_status" = 0 ] && [ "$lost" = 0 ]; then
    log "rehearsal clean: install and compile ran on a clone of $dir and lost no file ($rehearsal)"
    return 0
  fi
  log "rehearsal failed: install=$install_status compile=$compile_status agmsg=$agmsg_status lost=$lost ($rehearsal/result.txt)"
  if [ "$lost" != 0 ]; then
    log "files that disappeared, all in $rehearsal/lost.txt:"
    head -n 20 "$rehearsal/lost.txt" | sed 's/^/  /' >&2
  fi
  exit 1
}

# APM picks cache, config and temp locations from more than HOME (APM_CACHE_DIR, XDG_*, TMPDIR), and git honours
# tokens, proxies and askpass from the environment, so apm starts from an empty environment plus this allowlist, with
# its temp directory inside HOME.
run_apm() {
  local home="$1" var
  shift
  mkdir -p "$home/.cache/apm-native-tmp"
  local env_args=(HOME="$home" PATH="$PATH" TMPDIR="$home/.cache/apm-native-tmp" LANG="${LANG:-C.UTF-8}")
  for var in LC_ALL TERM PYTHONUTF8 GIT_CONFIG_GLOBAL GIT_CONFIG_NOSYSTEM GIT_CEILING_DIRECTORIES; do
    if [ -n "${!var:-}" ]; then env_args+=("$var=${!var}"); fi
  done
  (cd "$home" && env -i "${env_args[@]}" "$APM_BIN" "$@")
}

# Anything apm could write through to a file outside HOME: a symlink in HOME that resolves outside it (or is broken),
# and a regular file there with another hard link.
shared_entries() {
  local home="$1" link target
  find "$home" -type l | LC_ALL=C sort | while IFS= read -r link; do
    # GNU realpath resolves a link whose last component is missing, so test the target first.
    if [ ! -e "$link" ] || ! target="$(realpath "$link" 2>/dev/null)"; then
      printf '  %s (broken)\n' "$link"
      continue
    fi
    case "$target/" in
      "$home/"*) ;;
      *) printf '  %s -> %s\n' "$link" "$target" ;;
    esac
  done
  find "$home" -type f -links +1 | LC_ALL=C sort | sed 's/^/  /; s/$/ (hard link)/'
}

# apm reads ~/.apm/config.json with json.load and takes temp_dir and other locations from it. Decode it the same way
# and allow only default_client and prefer_ssh, which move no write location.
assert_default_apm_config() {
  local config="$1/.apm/config.json" extra
  [ -e "$config" ] || return 0
  extra="$(python3 -c 'import json, sys; print(" ".join(sorted(set(json.load(open(sys.argv[1], encoding="utf-8"))) - {"default_client", "prefer_ssh"})))' "$config")" ||
    fail "$config is not a JSON object apm could read"
  [ -z "$extra" ] || fail "$config sets $extra; only default_client and prefer_ssh may be set there"
}

main() {
  local command="${1:-plan}"
  [ $# -eq 0 ] || shift
  case "$command" in
    plan) cmd_plan "$@" ;;
    render) cmd_render "$@" ;;
    apply) cmd_apply "$@" ;;
    backup) cmd_backup "$@" ;;
    rehearse) cmd_rehearse "$@" ;;
    -h | --help | help) usage ;;
    *) usage >&2; exit 2 ;;
  esac
}

main "$@"
