#!/usr/bin/env bash
set -euo pipefail

COMMAND="${1:-}"
if [ "$#" -gt 0 ]; then
  shift
fi

SCRIPT_PATH="${BASH_SOURCE[0]}"
while [ -L "$SCRIPT_PATH" ]; do
  SCRIPT_DIR=$(CDPATH='' cd -P -- "$(dirname -- "$SCRIPT_PATH")" && pwd)
  LINK_TARGET=$(readlink "$SCRIPT_PATH")
  case "$LINK_TARGET" in
    /*) SCRIPT_PATH="$LINK_TARGET" ;;
    *) SCRIPT_PATH="$SCRIPT_DIR/$LINK_TARGET" ;;
  esac
done
SCRIPT_DIR=$(CDPATH='' cd -P -- "$(dirname -- "$SCRIPT_PATH")" && pwd)
REPO_ROOT=$(CDPATH='' cd -- "$SCRIPT_DIR/.." && pwd)
unset LINK_TARGET SCRIPT_PATH

# Resolved from the entry script's physical location so library and awk paths
# work from another cwd and when the entry script itself is a symlink.
APM_LIB_DIR="$SCRIPT_DIR/lib"
APM_AWK_DIR="$APM_LIB_DIR"

# After the native cutover $HOME/.apm is a consumer (apm.yml, apm.lock.yaml, apm_modules), not the authoring checkout.
. "$APM_LIB_DIR/shell-common.sh"
. "$APM_LIB_DIR/workspace-core.sh"

WORKSPACE_DIR="${APM_WORKSPACE_DIR:-$(default_workspace_dir)}"
WORKSPACE_REPO="${APM_WORKSPACE_REPO:-https://github.com/jey3dayo/apm-workspace.git}"
OPENCODE_INSTRUCTIONS_OUTPUT="${APM_OPENCODE_OUTPUT:-$HOME/.config/opencode/AGENTS.md}"
CATALOG_INSTRUCTIONS_FILE_NAME="ai-collaboration.instructions.md"
# The first line of every root context file `apm compile` writes (apm_cli/compilation/constants.py).
APM_GENERATED_ROOT_MARKER="<!-- Generated by APM CLI from .apm/ primitives -->"
CATALOG_DIR_NAME="catalog"
LEARNING_INTAKE_PENDING_WARN_THRESHOLD=10

. "$APM_LIB_DIR/host-mcp.sh"
. "$APM_LIB_DIR/learning-intake.sh"
. "$APM_LIB_DIR/catalog-instructions.sh"
. "$APM_LIB_DIR/catalog-inventory.sh"
. "$APM_LIB_DIR/catalog-validation.sh"
. "$APM_LIB_DIR/doctor.sh"

if [ "${BASH_SOURCE[0]}" = "${0}" ]; then
  case "$COMMAND" in
    setup:mcp:host) cmd_setup_host_mcp ;;
    sync:mcp:global) cmd_sync_global_mcp ;;
    sync:opencode) cmd_sync_opencode ;;
    validate) cmd_validate ;;
    validate:catalog) cmd_validate_catalog ;;
    doctor) cmd_doctor ;;
    doctor-intake) cmd_doctor_intake ;;
    *)
      fail "unknown command: $COMMAND"
      ;;
  esac
fi
