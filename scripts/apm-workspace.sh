  lock_path="$WORKSPACE_DIR/apm.lock.yaml"
  [ -f "$lock_path" ] || fail "Lock file not found: $lock_path"

  awk -f "$APM_AWK_DIR/lockfile-dependencies.awk" "$lock_path"
