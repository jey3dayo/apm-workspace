validate_skill_id() {
  skill_id="$1"

  case "$skill_id" in
    "" | . | .. | */* | *\\* | :* | *: | *::*)
      fail "Invalid skill id: $skill_id"
      ;;
  esac

  case "$skill_id" in
    [A-Za-z0-9]*)
      ;;
    *)
      fail "Invalid skill id: $skill_id"
      ;;
  esac

  case "$skill_id" in
    *[!A-Za-z0-9._:-]*)
      fail "Invalid skill id: $skill_id"
      ;;
  esac
}

validate_skill_path_segments() {
  original_value="$1"
  shift

  if [ "$#" -eq 0 ]; then
    fail "Invalid skill path: $original_value"
  fi

  for segment in "$@"; do
    case "$segment" in
      "" | . | .. | */* | *\\*)
        fail "Invalid skill path: $original_value"
        ;;
      [A-Za-z0-9]*)
        ;;
      *)
        fail "Invalid skill path: $original_value"
        ;;
    esac

    case "$segment" in
      *[!A-Za-z0-9._-]*)
        fail "Invalid skill path: $original_value"
        ;;
    esac
  done
}

# Sets SKILL_PATH to "<root>/<seg1>/<seg2>/..." for a colon-separated skill id.
# Validates in the current shell so a failure aborts the script, not a subshell.
skill_path_from_root() {
  SKILL_PATH_ROOT="$1"
  skill_id="$2"
  validate_skill_id "$skill_id"
  old_ifs=$IFS
  IFS=':'
  # shellcheck disable=SC2086
  set -- $skill_id
  IFS=$old_ifs
  validate_skill_path_segments "$skill_id" "$@"

  SKILL_PATH="$SKILL_PATH_ROOT"
  for segment in "$@"; do
    SKILL_PATH="$SKILL_PATH/$segment"
  done
}

skill_id_to_manifest_path() {
  skill_path_from_root "" "$1"
  printf '%s\n' "${SKILL_PATH#/}"
}

